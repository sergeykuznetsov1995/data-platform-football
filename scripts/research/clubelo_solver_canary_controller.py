class Refusal(ValueError):
    """Messages are a fixed allowlist, never raw exception text."""

    def __init__(self, reason="invalid_evidence"):
        self.reason = reason if reason in REASONS else "invalid_evidence"
        super().__init__(self.reason)


def need(condition, reason="invalid_evidence"):
    if not condition:
        raise Refusal(reason)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def digest(value):
    return isinstance(value, str) and re.fullmatch(r"[0-9a-f]{64}", value) is not None


def image_id(value):
    return isinstance(value, str) and value.startswith("sha256:") and digest(value[7:])


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False).encode("ascii")


def safe_path(value, *, directory=False, secret=False):
    """No symlink components, hard links, unsafe owners/modes or runtime trees.

    Root, runtime service and current-user owners are allowed. Group-writable
    ancestors require uid=gid=0 and no world-write bit. World-writable ancestors
    are forbidden except root-owned sticky /tmp. The leaf must be private.
    """
    need(isinstance(value, str) and value.startswith("/") and "\x00" not in value)
    path = Path(value)
    need(str(path) == value and ".." not in path.parts)
    for part in path.parts:
        need(not (part in {"proc", "sys", "dev", "watchdog", "espn-deploy"}
                  or part.endswith(("-runtime", "-deliveries", "_backfill", "_increment"))
                  or part.startswith((".prev-", ".pre-pin-"))))
    allowed_owners = {0, 1000, 50000, os.geteuid()}
    current = Path(path.anchor)
    for part in path.parts[1:]:
        current /= part
        info = current.lstat()
        need(not stat.S_ISLNK(info.st_mode))
        need(info.st_uid in allowed_owners)
        if current != path:
            need(stat.S_ISDIR(info.st_mode))
            need(not info.st_mode & 0o022 or
                 (info.st_uid == 0 and info.st_gid == 0 and not info.st_mode & 0o002) or
                 (current == Path("/tmp") and info.st_uid == 0 and info.st_mode & stat.S_ISVTX))
    info = path.lstat()
    need(info.st_uid in allowed_owners)
    need(not info.st_mode & (0o077 if secret or directory else 0o022))
    need(stat.S_ISDIR(info.st_mode) if directory else
         (stat.S_ISREG(info.st_mode) and info.st_nlink == 1))
    return path


def directory(path, allowed=None):
    path = safe_path(str(path), directory=True)
    if allowed is not None:
        need({p.name for p in path.iterdir()} <= set(allowed))
        for child in path.iterdir():
            safe_path(str(child), secret=True)
    return path


def read_json(path):
    path = safe_path(str(path))
    need(path.stat().st_size <= 8 * 1024**2)
    return harness.decode(path.read_text(encoding="ascii"))


def replace_json(path, value):
    """Reuse the observer's fsync + replace helper, including no-follow opens."""
    path = Path(path)
    directory(path.parent)
    if path.exists() or path.is_symlink():
        safe_path(str(path), secret=True)
    with observer._directory(path.parent) as fd:
        observer._atomic(fd, path.name, value)


def block(index):
    need(type(index) is int and 0 <= index < 3)
    arms = ["control"] * 20 + ["candidate"] * 20
    random.Random(2251 + index).shuffle(arms)
    return arms


def reservation(spent, daily_cap):
    need(harness._integer(spent) and harness._integer(daily_cap))
    cap = min(daily_cap, (MAX_BYTES - spent) // 3)
    need(cap > 0, "byte_cap")
    return cap


def rate_delay(starts, now):
    need(harness._number(now) and all(harness._number(t) and t <= now for t in starts))
    need(starts == sorted(starts))
    recent = [t for t in starts if now - t < 60]
    return max(0, recent[-2] + 60 - now) if len(recent) >= 2 else 0


