class Executor:
    """Only the controller builds argv; raw child output stays in its slot.

    A runner timeout is UNKNOWN, never a retry. Cleanup stops the service's
    project-labelled containers, including a surviving compose-run container.
    """

    def __call__(self, argv, *, env, output=None, timeout=60):
        if output is None:
            result = subprocess.run(argv, env=env, stdin=subprocess.DEVNULL,
                                    stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                    timeout=timeout, check=False)
            need(result.returncode == 0, "execution_failed")
            need(len(result.stdout) <= 8 * 1024**2)
            return result.stdout.decode("ascii")
        fd = os.open(output, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
        with os.fdopen(fd, "wb") as stream:
            result = subprocess.run(argv, env=env, stdin=subprocess.DEVNULL,
                                    stdout=stream, stderr=subprocess.STDOUT,
                                    timeout=timeout, check=False)
            stream.flush()
            os.fsync(stream.fileno())
        return result.returncode


class Controller:
    def __init__(self, plan, *, env_file, token_file, execute=None,
                 clock=time.time, sleep=time.sleep):
        self.plan = plan
        self.env_file = str(safe_path(str(env_file), secret=True))
        self.token_file = str(safe_path(str(token_file), secret=True))
        need(self.env_file != self.token_file)
        self.secret_metadata = self._secret_metadata()
        self.execute = execute or Executor()
        self.clock, self.sleep = clock, sleep
        self.state = None
        self.owned = False
        self.reports = []
        self._validate_plan()
        self.plan_hash = sha(canonical(plan))
        self.state_path = Path(plan["state_dir"]) / "state.json"
        self.env = self._environment()

    def _secret_metadata(self):
        result = []
        for path in (self.env_file, self.token_file):
            info = safe_path(path, secret=True).stat()
            result.append((info.st_dev, info.st_ino, info.st_size, info.st_mtime_ns, info.st_ctime_ns, info.st_mode))
        return result

    def _validate_plan(self):
        p = self.plan
        need(type(p) is dict and set(p) == PLAN_KEYS and p["schema"] == PLAN_SCHEMA)
        need(harness._identity(p["experiment"]) and
             p["project"] == "clubelo-canary-" + p["experiment"].lower())
        need(re.fullmatch(r"clubelo-canary-[a-z0-9][a-z0-9_-]{0,47}", p["project"]) is not None)
        need(type(p["images"]) is dict and set(p["images"]) == {*ARMS, "gateway", "runner"})
        for ref in p["images"].values():
            need(isinstance(ref, str) and re.fullmatch(r"[a-zA-Z0-9./:_-]+@sha256:[0-9a-f]{64}", ref))
        need(p["images"]["runner"] == RUNNER_IMAGE)
        need(p["images"]["control"] != p["images"]["candidate"])
        need(set(p["shared"]) == SHARED and all(digest(v) for v in p["shared"].values()))
        need(len(set(p["shared"].values())) == 3)
        need(p["gateway_health_path"] in {"/", "/health", "/healthz"})
        need(harness._integer(p["daily_lease_cap"]) and 0 < p["daily_lease_cap"] <= LEASE_BYTES)
        need(harness._number(p["deadline_epoch"]))
        need(isinstance(p["commit"], str) and re.fullmatch(r"[0-9a-f]{40}", p["commit"]))
        need(digest(p["diff_sha256"]))
        need(type(p["slots"]) is list and 1 <= len(p["slots"]) <= MAX_RUNS)
        dirs = [p[k] for k in ("state_dir", "code_dir", "release_dir", "gateway_state_dir")]
        need(set(p["preflight_dirs"]) == set(ARMS))
        dirs.extend(p["preflight_dirs"].values())
        for slot in p["slots"]:
            need(set(slot) == {"output", "observers"} and set(slot["observers"]) == set(ARMS))
            dirs += [slot["output"], *slot["observers"].values()]
        for path in dirs:
            directory(path)
        for index, first in enumerate(dirs):
            for second in dirs[index + 1:]:
                need(first != second and Path(first) not in Path(second).parents
                     and Path(second) not in Path(first).parents)
        for secret in (self.env_file, self.token_file):
            need(all(Path(d) not in Path(secret).parents for d in dirs))
        for key in ("compose", "dag", "local_evidence"):
            safe_path(p[key])
            need(p[key] not in {self.env_file, self.token_file})
        # Missing natural-traffic evidence is a final INCONCLUSIVE, not a reason
        # to create traffic or substitute synthetic observations.
        safe_path(str(Path(p["traffic_evidence"]).parent), directory=True)
        need(Path(p["traffic_evidence"]).is_absolute())
        need(p["traffic_evidence"] not in {self.env_file, self.token_file})
        directory(p["state_dir"], {"controller.lock", "state.json", "preflight.json"})
        need(type(p["hashes"]) is dict and all(digest(v) for v in p["hashes"].values()))
        self.verify_hashes()

    def verify_hashes(self):
        p = self.plan
        actual = {"compose": sha(safe_path(p["compose"]).read_bytes()),
                  "dag": sha(safe_path(p["dag"]).read_bytes())}
        need(Path(p["compose"]).parent / "solver_canary_dag.py" == Path(p["dag"]))
        for prefix, root in (("code", p["code_dir"]), ("release", p["release_dir"])):
            root = Path(root)
            for item in root.rglob("*"):
                need(not item.is_symlink())
                if item.is_dir():
                    directory(item)
                    continue
                safe_path(str(item))
                relative = item.relative_to(root).as_posix()
                need(not any(word in relative.lower() for word in
                             (".env", "token", "credential", "secret", "proxy_pool", ".git/")))
                actual[prefix + "/" + relative] = sha(item.read_bytes())
        need(actual == p["hashes"])
        need({"code/scripts/research/clubelo_solver_canary.py",
              "code/scripts/research/clubelo_canary_solver_instrumentation.py"} <= set(actual))

    def _environment(self):
        p = self.plan
        result = {"PATH": "/usr/local/bin:/usr/bin:/bin", "HOME": "/nonexistent",
                  "CLUBELO_GATEWAY_IMAGE": p["images"]["gateway"],
                  "CLUBELO_RELEASE_ROOT": p["release_dir"],
                  "CLUBELO_GATEWAY_STATE_HOST_DIR": p["gateway_state_dir"],
                  "CLUBELO_CANARY_GATEWAY_UID": "50000", "CLUBELO_CANARY_GATEWAY_GID": "0",
                  "CLUBELO_CANARY_SOLVER_UID": "1000", "CLUBELO_CANARY_SOLVER_GID": "1000",
                  "CLUBELO_CANARY_RUNNER_UID": "50000", "CLUBELO_CANARY_RUNNER_GID": "0",
                  "CLUBELO_CANARY_CODE_DIR": p["code_dir"],
                  "CLUBELO_CANARY_CONTROL_TOKEN_FILE": self.token_file}
        for arm in ARMS:
            repo, pin = p["images"][arm].split("@sha256:")
            result["CLUBELO_CANARY_" + arm.upper() + "_REPOSITORY"] = repo
            result["CLUBELO_CANARY_" + arm.upper() + "_DIGEST"] = pin
        return result

    def _slot_env(self, slot, arm, run_id):
        env = dict(self.env)
        env.update(CLUBELO_CANARY_ARM=arm, CLUBELO_CANARY_RUN_ID=run_id,
                   CLUBELO_CANARY_SELECTED_OBSERVER_DIR=slot["observers"][arm],
                   CLUBELO_CANARY_OUTPUT_DIR=slot["output"])
        for side in ARMS:
            env["CLUBELO_CANARY_" + side.upper() + "_OBSERVER_DIR"] = slot["observers"][side]
        return env

    def compose(self, operation, services, env, *, output=None, cap=None):
        need(services and all(s in SERVICES for s in services))
        need(self._secret_metadata() == self.secret_metadata)
        base = ["docker", "compose", "--project-name", self.plan["project"],
                "--file", self.plan["compose"], "--env-file", self.env_file]
        if operation == "up":
            need("runner" not in services)
            args = ["up", "-d", "--no-deps", *services]
        elif operation == "run":
            need(services == ["runner"] and cap == LEASE_BYTES)
            args = ["run", "--rm", "--no-deps", "-e", "CLUBELO_PROXY_MAX_BYTES=" + str(cap), "runner"]
        elif operation == "stop":
            args = ["stop", "--timeout", "30", *services]
        elif operation == "rm":
            args = ["rm", "-f", *services]
        else:
            raise Refusal()
        return self.execute(base + args, env=env, output=output,
                            timeout=RUN_SECONDS if operation == "run" else 120)

    def inspect_container(self, identity):
        need(digest(identity))
        row = harness.decode(self.execute(["docker", "inspect", "--type", "container", "--format",
                                          CONTAINER_FORMAT, identity], env=self.env))
        need(set(row) == {"id", "image", "status", "oom", "restarts", "project", "service",
                          "config_hash", "networks", "mounts"})
        need(row["id"] == identity and image_id(row["image"]))
        need(row["status"] in {"running", "exited", "created", "dead", "paused", "restarting"})
        need(type(row["oom"]) is bool and harness._integer(row["restarts"]))
        need(digest(row["config_hash"]))
        for key in ("project", "service"):
            need(isinstance(row[key], str) and re.fullmatch(r"[a-zA-Z0-9_.-]{1,128}", row[key]))
        need(type(row["networks"]) is dict and type(row["mounts"]) is list)
        networks = {}
        for name, item in row["networks"].items():
            need(re.fullmatch(r"[a-zA-Z0-9_.-]{1,128}", name) and digest(item["NetworkID"]))
            networks[name] = item["NetworkID"]
        row["networks"] = networks
        # Mount paths never leave this method. Refuse a Docker socket in ANY
        # disposable container, including aliases mounted at another target.
        if row["project"] == self.plan["project"]:
            for mount in row["mounts"]:
                need(not any("docker.sock" in str(mount.get(k, "")) or
                             "containerd.sock" in str(mount.get(k, "")) for k in ("Source", "Destination")))
        del row["mounts"]
        return row

    def inventory(self, *, own=False):
        argv = ["docker", "ps", "--all", "--quiet", "--no-trunc"]
        if own:
            argv += ["--filter", "label=com.docker.compose.project=" + self.plan["project"]]
        ids = self.execute(argv, env=self.env).splitlines()
        need(len(ids) == len(set(ids)) and all(digest(i) for i in ids))
        rows = [self.inspect_container(i) for i in ids]
        if own:
            need(all(r["project"] == self.plan["project"] and r["service"] in SERVICES for r in rows))
        return rows

    def shared_snapshot(self):
        result = {name: self.inspect_container(identity) for name, identity in self.plan["shared"].items()}
        need(all(row["project"] != self.plan["project"] and row["status"] == "running"
                 and not row["oom"] for row in result.values()), "shared_drift")
        return result

    def unchanged(self):
        need(self.shared_snapshot() == self.state["baseline"], "shared_drift")

    def _network_check(self, rows):
        """Both isolated networks must be exclusive to these four services."""
        ids = {value for row in rows for value in row["networks"].values()}
        names = {name for row in rows for name in row["networks"]}
        need(names == {self.plan["project"] + "_internal", self.plan["project"] + "_egress"})
        result = {}
        for identity in sorted(ids):
            net = harness.decode(self.execute(["docker", "network", "inspect", "--format",
                                              NETWORK_FORMAT, identity], env=self.env))
            need(set(net) == {"id", "internal", "project", "members"} and net["id"] == identity)
            need(net["project"] == self.plan["project"] and type(net["internal"]) is bool)
            need(set(net["members"] or {}) <= {row["id"] for row in rows})
            result[identity] = net["internal"]
        need(len(result) == 2 and sorted(result.values()) == [False, True])
        for row in rows:
            expected = {self.plan["project"] + "_internal"}
            if row["service"] in {"runner", "clubelo-canary-gateway"}:
                expected.add(self.plan["project"] + "_egress")
            need(set(row["networks"]) == expected)
            internal_id = row["networks"][self.plan["project"] + "_internal"]
            need(result[internal_id] is True)
        return result

    def save(self):
        replace_json(self.state_path, self.state)

    @contextmanager
    def lock(self):
        directory(self.plan["state_dir"], {"controller.lock", "state.json", "preflight.json"})
        path = Path(self.plan["state_dir"]) / "controller.lock"
        fd = os.open(path, os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW | os.O_NONBLOCK, 0o600)
        resource_fds = []
        try:
            info = os.fstat(fd)
            need(stat.S_ISREG(info.st_mode) and info.st_nlink == 1 and not info.st_mode & 0o077)
            fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
            # Also serialize any accidental second plan referring to the same
            # persistent gateway state, without extra gate files.
            for root in [self.plan["gateway_state_dir"]]:
                resource = os.open(root, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
                resource_fds.append(resource)
                fcntl.flock(resource, fcntl.LOCK_EX | fcntl.LOCK_NB)
            yield
        finally:
            for resource in resource_fds:
                os.close(resource)
            os.close(fd)

    def load(self):
        value = read_json(self.state_path)
        need(type(value) is dict and set(value) == STATE_KEYS and value["schema"] == SCHEMA)
        need(value["plan_sha256"] == self.plan_hash)
        need(value["phase"] in {"executing", "stopped", "finished"})
        need(value["stop_reason"] is None or value["stop_reason"] in REASONS)
        need(type(value["unknown"]) is bool)
        need(type(value["resources_authorized"]) is bool)
        need(harness._number(value["started_epoch"]) and harness._number(value["deadline_epoch"]))
        need(0 < value["deadline_epoch"] - value["started_epoch"] <= MAX_SECONDS)
        need(value["deadline_epoch"] == self.plan["deadline_epoch"])
        need(value["started_utc"] == harness.utc(value["started_epoch"]) and
             value["deadline_utc"] == harness.utc(value["deadline_epoch"]))
        for key in ("attempts", "provider_bytes", "candidate_failures", "block_index"):
            need(harness._integer(value[key]))
        need(value["attempts"] <= MAX_ATTEMPTS and value["provider_bytes"] <= MAX_BYTES)
        need(value["block_index"] <= 2 and value["candidate_failures"] <= 5)
        need(type(value["run_starts"]) is list and len(value["run_starts"]) <= MAX_RUNS)
        rate_delay(value["run_starts"], self.clock())
        need(len(value["run_starts"]) <= len(self.plan["slots"]))
        need(all(value["started_epoch"] <= t <= value["deadline_epoch"]
                 for t in value["run_starts"]))
        need(all(value["run_starts"][n] - value["run_starts"][n - 2] >= 60
                 for n in range(2, len(value["run_starts"]))))
        need(type(value["completed_runs"]) is list and len(value["completed_runs"]) <= len(value["run_starts"]))
        self.state = value
        self.reports = []
        failures = 0
        for index, saved in enumerate(value["completed_runs"]):
            need(set(saved) == {"run_id", "arm", "sha256"} and digest(saved["sha256"]))
            arm = block(index // 40)[index % 40]
            need(saved["arm"] == arm and saved["run_id"] == self.run_id(index))
            report = read_json(Path(self.plan["slots"][index]["output"]) / "report.json")
            need(sha(canonical(report)) == saved["sha256"])
            validate_report(report)
            need(report["run_id"] == saved["run_id"] and report["arm"] == arm)
            need(value["run_starts"][index] == report["started_epoch"])
            need(report["finished_epoch"] <= value["deadline_epoch"])
            audit_observer(self.plan["slots"][index]["observers"][arm], report)
            if arm == "candidate":
                failures = 0 if report["validated_clearance"] else failures + 1
            self.reports.append(report)
        need(value["attempts"] == sum(len(r["attempts"]) for r in self.reports))
        need(value["provider_bytes"] == sum(r["accounting"]["total_bytes"] for r in self.reports))
        need(value["candidate_failures"] == failures)
        if value["phase"] == "finished":
            need(value["active"] is None and not value["unknown"] and value["finished_epoch"] is not None)
        return value

    def run_id(self, index):
        return "canary-" + self.plan["experiment"] + "-" + str(index + 1).zfill(4)

    def _local_proof(self, images):
        proof = read_json(self.plan["local_evidence"])
        need(type(proof) is dict and set(proof) == {
            "schema", "status", "local_only", "cleanup_complete", "reviewed", "images", "code_hashes",
            "airflow_smoke", "focused_unit"})
        need(proof["schema"] == LOCAL_SCHEMA and proof["status"] == "PASS"
             and proof["local_only"] is True and proof["cleanup_complete"] is True
             and proof["reviewed"] is True)
        need(proof["images"] == {arm: images[arm]["resolved"] for arm in ARMS})
        need(proof["code_hashes"] == self.plan["hashes"])
        smoke = proof["airflow_smoke"]
        need(type(smoke) is dict and set(smoke) == {
            "status", "real_airflow", "runner_image", "evidence_sha256"})
        need(smoke["status"] == "PASS" and smoke["real_airflow"] is True
             and smoke["runner_image"] == images["runner"]["resolved"]
             and digest(smoke["evidence_sha256"]))
        unit = proof["focused_unit"]
        need(type(unit) is dict and set(unit) == {
            "status", "passed", "failed", "skipped", "evidence_sha256"})
        need(unit["status"] == "PASS" and harness._integer(unit["passed"]) and unit["passed"] > 0
             and type(unit["failed"]) is int and unit["failed"] == 0
             and type(unit["skipped"]) is int and unit["skipped"] == 0
             and digest(unit["evidence_sha256"]))
        return sha(canonical(proof))

    def _images(self):
        images = {}
        for name, reference in self.plan["images"].items():
            row = harness.decode(self.execute(["docker", "image", "inspect", "--format", IMAGE_FORMAT,
                                              reference], env=self.env))
            need(set(row) == {"id", "digests"} and image_id(row["id"]))
            repository, separator, digest = reference.rpartition("@")
            need(separator == "@" and image_id(digest))
            # Docker RepoDigests omit tags, but registry ports remain part of the repository.
            if ":" in repository.rsplit("/", 1)[-1]:
                repository = repository.rsplit(":", 1)[0]
            equivalent = repository + "@" + digest
            need(type(row["digests"]) is list and
                 (reference in row["digests"] or equivalent in row["digests"]))
            images[name] = {"requested": reference, "resolved": row["id"]}
        return images

    def _deactivate(self, root):
        path = Path(root) / observer.ACTIVE_FILE
        if path.exists():
            value = read_json(path)
            need(set(value) == observer._ACTIVE_KEYS)
            value["active"] = False
            replace_json(path, value)

    def _inactive(self, root, run_id, arm, now):
        replace_json(Path(root) / observer.ACTIVE_FILE,
                     dict(schema=observer.ACTIVE_SCHEMA, run_id=run_id, arm=arm,
                          started=now, expires=now, active=False))

    def _stop_solvers(self, env):
        self.compose("stop", ["solver-control", "solver-candidate"], env)
        self.compose("rm", ["solver-control", "solver-candidate"], env)

    def preflight(self):
        """Index/health GETs only; no solve requests during preflight."""
        self.verify_hashes()
        images = self._images()
        proof_hash = self._local_proof(images)
        need(not self.inventory(own=True))
        # A reused project/network is not a fresh isolated experiment.
        network_ids = self.execute(["docker", "network", "ls", "--quiet", "--no-trunc", "--filter",
                                    "label=com.docker.compose.project=" + self.plan["project"]], env=self.env)
        need(not network_ids.strip())
        self.state["baseline"] = self.shared_snapshot()
        inventory = self.inventory()
        shared_networks = {n for row in self.state["baseline"].values() for n in row["networks"].values()}
        consumers = {"whoscored", "sofifa"}
        for row in inventory:
            if row["id"] not in self.plan["shared"].values() and shared_networks.intersection(row["networks"].values()):
                # Conservative discovery: an unknown peer needs its own natural
                # traffic proof; absence cannot silently become no regression.
                consumers.add(row["service"].lower())
        directory(self.plan["gateway_state_dir"], set())
        for slot in self.plan["slots"]:
            directory(slot["output"], set())
            for root in slot["observers"].values():
                directory(root, set())
        for root in self.plan["preflight_dirs"].values():
            directory(root, set())
        self.state["resources_authorized"] = True
        self.save()
        versions = {}
        snapshots = {}
        for arm in ARMS:
            root = directory(self.plan["preflight_dirs"][arm], set())
            now = self.clock()
            need(now + 120 <= self.state["deadline_epoch"], "deadline")
            run_id = "preflight-" + arm
            self.state["active"] = {"kind": "preflight", "arm": arm, "run_id": run_id}
            self.save()
            observer.write_active_run(root, run_id, arm, now, now + 120)
            slot = {"observers": self.plan["preflight_dirs"], "output": self.plan["slots"][0]["output"]}
            env = self._slot_env(slot, arm, run_id)
            self.compose("up", ["clubelo-canary-gateway", "solver-" + arm], env)
            rows = self.inventory(own=True)
            need({r["service"] for r in rows} == {"clubelo-canary-gateway", "solver-" + arm} and len(rows) == 2)
            self._network_check(rows)
            for row in rows:
                key = arm if row["service"] == "solver-" + arm else "gateway"
                need(row["image"] == images[key]["resolved"] and row["status"] == "running"
                     and not row["oom"] and row["restarts"] == 0)
                snapshots[key] = row
            solver = snapshots[arm]
            versions[arm] = harness.decode(self.execute(["docker", "exec", solver["id"], "python", "-c",
                                                        SOLVER_HEALTH], env=self.env))
            need(set(versions[arm]) == {"solver", "chrome"})
            need(all(isinstance(v, str) and re.fullmatch(r"[0-9]+(?:\.[0-9]+){1,3}", v)
                     for v in versions[arm].values()))
            healthy = harness.decode(self.execute(["docker", "exec", snapshots["gateway"]["id"],
                                                   "python", "-c", GATEWAY_HEALTH,
                                                   self.plan["gateway_health_path"]], env=self.env))
            need(type(healthy) is dict and set(healthy) == {
                "healthy", "daily_budget_bytes", "daily_total_bytes", "max_lease_bytes",
                "max_active_leases", "source_mode"})
            need(healthy["healthy"] is True)
            for key, expected in (("daily_budget_bytes", MAX_BYTES),
                                  ("max_lease_bytes", LEASE_BYTES), ("max_active_leases", 1)):
                need(type(healthy[key]) is int and healthy[key] == expected)
            need(harness._number(healthy["daily_total_bytes"]) and healthy["daily_total_bytes"] >= 0)
            need(healthy["source_mode"] == "shared-no-whoscored")
            self._stop_solvers(env)
            need(observer.read_events(root, run_id) == [])
            self._deactivate(root)
            self.unchanged()
            self.state["active"] = None
            self.save()
        preflight = dict(images=images, versions=versions, gateway=snapshots["gateway"],
                         networks=snapshots["gateway"]["networks"], shared=self.state["baseline"],
                         consumers=sorted(consumers), local_proof_sha256=proof_hash,
                         code_hashes=self.plan["hashes"], commit=self.plan["commit"],
                         diff_sha256=self.plan["diff_sha256"])
        harness.atomic_report(Path(self.plan["state_dir"]) / "preflight.json", preflight)
        self.state["preflight"] = sha(canonical(preflight))
        self.save()

    def _preflight_evidence(self):
        value = read_json(Path(self.plan["state_dir"]) / "preflight.json")
        need(sha(canonical(value)) == self.state["preflight"])
        return value

    def _before_run(self):
        s = self.state
        need(self.owned and s["phase"] == "executing" and s["active"] is None and not s["unknown"],
             "unknown_execution")
        n = len(s["run_starts"])
        need(n == len(s["completed_runs"]), "unknown_execution")
        need(n < MAX_RUNS, "run_cap")
        need(n < len(self.plan["slots"]), "slots_exhausted")
        need(s["attempts"] + 3 <= MAX_ATTEMPTS, "attempt_cap")
        need(s["candidate_failures"] < 5, "five_candidate_failures")
        cap = reservation(s["provider_bytes"], self.plan["daily_lease_cap"])
        need(cap == LEASE_BYTES, "harness_byte_guard")
        while True:
            now = self.clock()
            need(now + RUN_SECONDS <= s["deadline_epoch"], "deadline")
            delay = rate_delay(s["run_starts"], now)
            if not delay:
                break
            self.sleep(min(delay, 60))
        self.unchanged()
        self.verify_hashes()
        preflight = self._preflight_evidence()
        need(self._images() == preflight["images"])
        self._local_proof(preflight["images"])
        traffic_path = Path(self.plan["traffic_evidence"])
        if traffic_path.exists():
            gate = traffic_gate(read_json(traffic_path), preflight["consumers"], s["started_epoch"], self.clock())
            need(gate["status"] != "FAIL", "other_source_regression")
            need(gate["status"] == "PASS")
        arm = block(n // 40)[n % 40]
        slot = self.plan["slots"][n]
        directory(slot["output"], set())
        for root in slot["observers"].values():
            directory(root, set())
        return n, arm, slot, cap

    def one_run(self):
        n, arm, slot, cap = self._before_run()
        run_id = self.run_id(n)
        now = self.clock()
        need(now + RUN_SECONDS <= self.state["deadline_epoch"], "deadline")
        self.state["block_index"] = n // 40
        self.state["run_starts"].append(now)
        self.state["active"] = {"kind": "run", "index": n, "arm": arm, "run_id": run_id}
        self.save()  # Durable intent precedes markers, container startup and traffic.
        other = next(side for side in ARMS if side != arm)
        self._inactive(slot["observers"][other], run_id, other, now)
        observer.write_active_run(slot["observers"][arm], run_id, arm, now, now + RUN_SECONDS)
        env = self._slot_env(slot, arm, run_id)
        self.compose("up", ["clubelo-canary-gateway", "solver-" + arm], env)
        rows = self.inventory(own=True)
        need(len(rows) == 2 and {r["service"] for r in rows} == {"clubelo-canary-gateway", "solver-" + arm})
        self._network_check(rows)
        proof = self._preflight_evidence()
        for row in rows:
            key = arm if row["service"] == "solver-" + arm else "gateway"
            need(row["image"] == proof["images"][key]["resolved"] and row["status"] == "running"
                 and row["restarts"] == 0 and not row["oom"])
            if key == "gateway":
                need(row == proof["gateway"])
        # Count the actual task launch conservatively as a start too: startup
        # delay must never shorten the rolling two-run interval.
        launch = self.clock()
        need(now <= launch < now + RUN_SECONDS and launch + RUN_SECONDS <= self.state["deadline_epoch"], "deadline")
        self.state["run_starts"][-1] = launch
        self.save()
        code = self.compose("run", ["runner"], env,
                            output=str(Path(slot["output"]) / "process.raw"), cap=cap)
        need(type(code) is int and code in (0, 1), "execution_failed")
        self._stop_solvers(env)  # No solver writers remain at the final join.
        output = directory(slot["output"], {"report.json", ".report.json.started", "process.raw"})
        need({p.name for p in output.iterdir()} == {"report.json", ".report.json.started", "process.raw"})
        report = read_json(output / "report.json")
        validate_report(report)
        need(report["run_id"] == run_id and report["arm"] == arm)
        need(launch <= report["started_epoch"] <= report["finished_epoch"] <= self.clock() <= now + RUN_SECONDS)
        events = observer.read_events(slot["observers"][arm], run_id)
        base = [{k: v for k, v in item.items() if k not in {"detection", "solved", "validated"}}
                for item in report["attempts"]]
        joined, totals = harness.join_observations(base, events, run_id, arm, report["page_validated"])
        need(joined == report["attempts"] and totals == report["detection"])
        need(report["invalid_solutions_forwarded"] == 0, "quota")
        need(all(lease["close_proof"] is None or lease["close_proof"]["total_bytes"] <= cap
                 for lease in report["accounting"]["leases"]), "quota")
        need(report["accounting"]["total_bytes"] <= 3 * cap, "quota")
        need(self.state["attempts"] + len(report["attempts"]) <= MAX_ATTEMPTS, "quota")
        need(self.state["provider_bytes"] + report["accounting"]["total_bytes"] <= MAX_BYTES, "quota")
        # The inactive journal must remain completely empty, without error markers.
        directory(slot["observers"][other], {observer.ACTIVE_FILE})
        self._deactivate(slot["observers"][arm])
        audit_observer(slot["observers"][arm], report)
        self.unchanged()
        # Use the actual run-once start for the next rolling-rate decision,
        # rather than the earlier compose/Airflow process launch timestamp.
        self.state["run_starts"][-1] = report["started_epoch"]
        self.state["attempts"] += len(report["attempts"])
        self.state["provider_bytes"] += report["accounting"]["total_bytes"]
        if arm == "candidate":
            self.state["candidate_failures"] = 0 if report["validated_clearance"] else self.state["candidate_failures"] + 1
        self.state["completed_runs"].append(dict(run_id=run_id, arm=arm, sha256=sha(canonical(report))))
        self.state["active"] = None
        self.reports.append(report)
        self.save()

    def cleanup(self):
        """Deactivate observers, remove only verified project resources, preserve data.

        Complete reports contain the authoritative DELETE close proofs. Unknown
        runs cannot be reconciled by guessing lease IDs or reading a secret. We
        terminate isolated processes/tunnels, retain their durable gateway state
        for owner reconciliation and explicitly withhold accounting finality.
        """
        result = dict(resources_removed=False, shared_unchanged=False,
                      accounting_final=False, observers_inactive=False)
        if not self.state["resources_authorized"]:
            self.state["cleanup"] = result
            self.save()
            return result
        result["observers_inactive"] = True
        for root in [*self.plan["preflight_dirs"].values(),
                     *(root for slot in self.plan["slots"] for root in slot["observers"].values())]:
            try:
                self._deactivate(root)
            except Exception:
                result["observers_inactive"] = False
        try:
            rows = self.inventory(own=True)
            net_ids = self.execute(["docker", "network", "ls", "--quiet", "--no-trunc", "--filter",
                                    "label=com.docker.compose.project=" + self.plan["project"]], env=self.env).splitlines()
            need(len(net_ids) == len(set(net_ids)) and all(digest(identity) for identity in net_ids))
            # Explicit container IDs cover compose-run orphans without targeting
            # a shared service name. Ownership is checked again before removal.
            for row in rows:
                need(self.inspect_container(row["id"])["project"] == self.plan["project"])
                self.execute(["docker", "stop", "--time", "30", row["id"]], env=self.env, timeout=60)
                self.execute(["docker", "rm", row["id"]], env=self.env)
            for identity in sorted(net_ids):
                net = harness.decode(self.execute(["docker", "network", "inspect", "--format",
                                                  NETWORK_FORMAT, identity], env=self.env))
                need(net["id"] == identity and net["project"] == self.plan["project"] and not net["members"])
                self.execute(["docker", "network", "rm", identity], env=self.env)
            need(not self.inventory(own=True))
            need(not self.execute(["docker", "network", "ls", "--quiet", "--no-trunc", "--filter",
                                   "label=com.docker.compose.project=" + self.plan["project"]], env=self.env).strip())
            result["resources_removed"] = True
        except Exception:
            pass
        try:
            self.unchanged()
            result["shared_unchanged"] = True
        except Exception:
            pass
        result["accounting_final"] = (not self.state["unknown"] and self.state["active"] is None
                                       and len(self.state["run_starts"]) == len(self.reports))
        self.state["cleanup"] = result
        self.state["active"] = None
        self.save()
        return result

    def run(self):
        with self.lock():
            # Never infer that a previous invocation was idle from a checkpoint.
            # No preflight/up/run is possible on ANY existing experiment state.
            if self.state_path.exists():
                self.load()
                raise Refusal("unknown_execution")
            now = self.clock()
            need(0 < self.plan["deadline_epoch"] - now <= MAX_SECONDS, "deadline")
            need(not (Path(self.plan["state_dir"]) / "preflight.json").exists())
            self.state = dict(schema=SCHEMA, plan_sha256=self.plan_hash,
                              started_epoch=now, deadline_epoch=self.plan["deadline_epoch"],
                              started_utc=harness.utc(now), deadline_utc=harness.utc(self.plan["deadline_epoch"]),
                              phase="executing", active=None, block_index=0, completed_runs=[], run_starts=[],
                              attempts=0, provider_bytes=0, candidate_failures=0,
                              stop_reason=None, baseline=None, preflight=None, cleanup=None,
                              unknown=False, finished_epoch=None, resources_authorized=False)
            self.save()
            self.owned = True
            try:
                self.preflight()
                while True:
                    need(self.state["candidate_failures"] < 5, "five_candidate_failures")
                    n = len(self.reports)
                    if n and n % 40 == 0 and minima(self.reports):
                        raise Refusal("sample_complete")
                    self.one_run()
            except BaseException as exc:
                reason = exc.reason if isinstance(exc, Refusal) else "invalid_evidence"
                self.state["stop_reason"] = reason
                self.state["unknown"] = self.state["active"] is not None or reason in {
                    "invalid_evidence", "execution_failed", "unknown_execution", "quota", "shared_drift"}
                self.state["phase"] = "stopped" if self.state["unknown"] else "finished"
                self.state["finished_epoch"] = self.clock()
                self.save()
                self.cleanup()
                self.owned = False
                if isinstance(exc, (KeyboardInterrupt, SystemExit)):
                    raise
            return self.report()

    def stop(self):
        with self.lock():
            self.load()
            if self.state["phase"] == "executing":
                self.state["unknown"] = True
            self.state["phase"] = "stopped"
            self.state["stop_reason"] = "operator_stop"
            self.state["finished_epoch"] = self.clock()
            self.save()
            self.cleanup()
            return self.report()

    def status(self):
        self.load()
        return dict(schema=SCHEMA, phase=self.state["phase"], runs=len(self.reports),
                    attempts=self.state["attempts"],
                    provider_bytes=self.state["provider_bytes"], stop_reason=self.state["stop_reason"],
                    review_required=self.state["unknown"] or self.state["phase"] == "executing")

    def report(self):
        self.load()
        statistical = harness.evaluate(self.reports)
        traffic = {"status": "INCONCLUSIVE", "sources": {}}
        try:
            proof = self._preflight_evidence()
            traffic = traffic_gate(read_json(self.plan["traffic_evidence"]), proof["consumers"],
                                   self.state["started_epoch"], self.state["finished_epoch"])
        except Exception:
            pass
        clean = self.state["cleanup"]
        rollback = (type(clean) is dict and set(clean) == {
            "resources_removed", "shared_unchanged", "accounting_final", "observers_inactive"}
            and all(v is True for v in clean.values()))
        certain = (rollback and self.state["phase"] == "finished" and not self.state["unknown"])
        status = "INCONCLUSIVE"
        if (certain and self.state["stop_reason"] == "sample_complete"
                and statistical["status"] != "INCONCLUSIVE" and traffic["status"] != "INCONCLUSIVE"):
            status = "PASS" if statistical["status"] == traffic["status"] == "PASS" else "FAIL"
        if self.state["stop_reason"] in {
                "five_candidate_failures", "shared_drift", "quota", "other_source_regression"}:
            status = "FAIL"
        return dict(status=status, statistics=statistical, other_sources=traffic,
                    rollback_pass=bool(rollback), stop_reason=self.state["stop_reason"],
                    review_required=not certain)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("run", "stop", "status", "report"))
    parser.add_argument("--plan", required=True)
    parser.add_argument("--env-file", required=True)
    parser.add_argument("--token-file", required=True)
    args = parser.parse_args(argv)
    try:
        controller = Controller(read_json(args.plan), env_file=args.env_file, token_file=args.token_file)
        result = getattr(controller, args.command)()
        print(json.dumps(result, sort_keys=True, allow_nan=False))
        return 0 if result.get("status") == "PASS" else 1
    except Exception:
        print('{"status":"INCONCLUSIVE","reasons":["invalid_or_unknown_controller_evidence"]}')
        return 2


