"""Bounded, disposable ClubElo experiment controller; no deployment authority.

The lead provisions and reviews a plan and the offline smoke proof before use.
``run`` is deliberately single-use: even a clean checkpoint left by a crashed
process is review-only. ``status`` and ``report`` never execute commands.

Plan v1 has exact keys documented by PLAN_KEYS below. Paths are absolute,
pre-provisioned, private and disjoint. ``slots`` contains up to 120 objects with
``output`` and ``observers`` (control/candidate directories). ``preflight_dirs``
contains two additional empty observer directories. ``hashes`` maps every file
under the frozen code/release trees to SHA256, using ``code/`` and ``release/``
prefixes, plus ``compose`` and ``dag``. No unlisted release files are accepted.
``images`` contains pinned references for control/candidate/gateway/runner;
``shared`` contains full container IDs for flaresolverr, clubelo-gateway and
airflow-scheduler. The gateway health path is an explicitly reviewed GET-only
index/health path. The env-file and token are separate CLI arguments: only
their filesystem metadata is inspected, never their contents.

Offline smoke v1 has exactly schema/status/local_only/cleanup_complete/reviewed,
images (control/candidate built sha256 IDs), code_hashes, airflow_smoke and
focused_unit. Airflow evidence has status/real_airflow/runner_image/evidence_sha256;
unit evidence has status/passed/failed/skipped/evidence_sha256. Evidence hashes
refer to the lead's retained real offline smoke and focused unit results.
Natural traffic
v1 has schema/sources; each source has baseline/current, with requests, errors,
p95_ms, start/end epoch and identity_sha256. These are sanitized aggregates,
not traffic generated by this controller. All outputs except process.raw are
strictly structured evidence. Never submit process.raw to a model.

Compatibility limit: the reviewed harness requires exactly 33554432 bytes per
lease. We calculate the three-lease reservation but stop if it is smaller;
changing that guard or the reviewed Compose is outside this controller.
The independent 2048 MiB provider-side cap remains provisioned by the owner;
the 2 GiB experiment limit here neither configures nor replaces that cap.
"""

