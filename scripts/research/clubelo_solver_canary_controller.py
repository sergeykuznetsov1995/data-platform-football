def validate_report(report):
    """The harness validates semantics; this layer rejects extra payload fields."""
    need(type(report) is dict and set(report) == {
        "schema", "run_id", "arm", "started_epoch", "finished_epoch", "actual_start_utc", "actual_end_utc",
        "attempts", "detection", "page_outcome", "page_validated", "validated_clearance", "no_challenge",
        "wire_bytes", "accounting", "invalid_solutions_forwarded", "complete", "errors"})
    harness._population([report])
    need(report["actual_start_utc"] == harness.utc(report["started_epoch"]) and
         report["actual_end_utc"] == harness.utc(report["finished_epoch"]))
    need(set(report["accounting"]) == {"complete", "total_bytes", "leases"})
    for attempt in report["attempts"]:
        need(set(attempt) == harness.ATTEMPT_KEYS | {
            "run_id", "started_epoch", "finished_epoch", "detection", "solved", "validated"})
    for lease in report["accounting"]["leases"]:
        need(set(lease) == {"lease_id", "acquisition", "constructed", "close_attempted", "close_failed",
                            "close_proof", "accounting_complete"})
        if lease["close_proof"] is not None:
            need(set(lease["close_proof"]) == set(harness.CLOSE_KEYS))
    return report


def audit_observer(root, report):
    """Read an inactive, stopped writer's journal without reactivating it."""
    root = directory(root, {observer.ACTIVE_FILE, observer.EVENT_FILE})
    active = read_json(root / observer.ACTIVE_FILE)
    need(type(active) is dict and set(active) == observer._ACTIVE_KEYS and active["active"] is False)
    observer._active(dict(active, active=True), report["arm"], report["started_epoch"])
    need(active["run_id"] == report["run_id"] and report["finished_epoch"] <= active["expires"])
    event_path = root / observer.EVENT_FILE
    events = observer._parse_events(event_path.read_bytes() if event_path.exists() else b"",
                                    report["run_id"], report["arm"])
    base = [{k: v for k, v in item.items() if k not in {"detection", "solved", "validated"}}
            for item in report["attempts"]]
    joined, totals = harness.join_observations(base, events, report["run_id"], report["arm"], report["page_validated"])
    need(joined == report["attempts"] and totals == report["detection"])


def traffic_gate(data, consumers, started, finished):
    """Insufficient samples and absent evidence are never measured regressions."""
    result = {"status": "INCONCLUSIVE", "sources": {}}
    try:
        need(set(data) == {"schema", "sources"} and data["schema"] == TRAFFIC_SCHEMA)
        missing = False
        failed = False
        for source in sorted(set(consumers) | {"whoscored", "sofifa"}):
            if source not in data["sources"]:
                missing = True
                result["sources"][source] = "missing"
                continue
            row = data["sources"][source]
            need(set(row) == {"baseline", "current"})
            for window in row.values():
                need(set(window) == {"requests", "errors", "p95_ms", "start", "end", "identity_sha256"})
                need(harness._integer(window["requests"]) and harness._integer(window["errors"])
                     and window["errors"] <= window["requests"])
                need(harness._number(window["p95_ms"]) and window["p95_ms"] >= 0)
                need(harness._number(window["start"]) and harness._number(window["end"])
                     and window["start"] < window["end"] and digest(window["identity_sha256"]))
            before, after = row["baseline"], row["current"]
            need(before["end"] <= started <= after["start"] < after["end"] <= finished)
            need(before["identity_sha256"] == after["identity_sha256"])
            # Comparable duration as well as version/config identity.
            need(before["end"] - before["start"] == after["end"] - after["start"])
            if min(before["requests"], after["requests"]) < 30:
                missing = True
                result["sources"][source] = "insufficient"
                continue
            passed = (after["errors"] / after["requests"] - before["errors"] / before["requests"]
                      <= 0.02 + 1e-12 and after["p95_ms"] <= 1.10 * before["p95_ms"] + 1e-12)
            result["sources"][source] = "PASS" if passed else "FAIL"
            failed |= not passed
        result["status"] = "FAIL" if failed else "INCONCLUSIVE" if missing else "PASS"
    except Exception:
        result["status"] = "INCONCLUSIVE"
    return result


