"""#1472: match parsing stays byte-identical to master and fast.

The golden file was generated by the parser of the base commit (before the
``schema_fingerprint`` hoist) from three real WhoScored match pages, and
regenerated for #1483 where only ``matches`` (header columns) and
``substitutions`` (``related_player_id``) changed.
"""

from __future__ import annotations

import gzip
import hashlib
import json
import time
from pathlib import Path

import pytest

from scrapers.whoscored.domain import WhoScoredScope
from scrapers.whoscored.parsers import (
    extract_matchcentre_event_types,
    parse_match_html,
    parse_profile_bundle,
)

FIXTURES = Path(__file__).resolve().parents[2] / "fixtures" / "whoscored"
GOLDEN = json.loads((FIXTURES / "match_golden.json").read_text(encoding="utf-8"))
SCOPE = WhoScoredScope("WS-test", "2526", "split_year")


def _html(game_id: int) -> str:
    with gzip.open(FIXTURES / f"match-{game_id}.raw.gz", "rt", encoding="utf-8") as handle:
        return handle.read()


def _digest(rows) -> str:
    digest = hashlib.sha256()
    for row in rows:
        digest.update(json.dumps(row, sort_keys=True, default=str).encode("utf-8"))
        digest.update(b"\n")
    return digest.hexdigest()


@pytest.mark.parametrize("game_id", [1952492, 1946345, 1955749])
def test_match_datasets_equal_master_golden(game_id):
    result = parse_match_html(_html(game_id), scope=SCOPE, game_id=game_id)

    actual = {
        name: {"rows": len(dataset.rows), "sha256": _digest(dataset.rows)}
        for name, dataset in result.datasets.items()
    }

    assert len(actual) == 7
    assert actual == GOLDEN[str(game_id)]


def test_heaviest_match_parses_under_two_seconds():
    html = _html(1952492)

    started = time.perf_counter()
    parse_match_html(html, scope=SCOPE, game_id=1952492)
    elapsed = time.perf_counter() - started

    assert elapsed < 2.0, f"match-1952492 parsed in {elapsed:.2f}s"


def test_match_header_reads_real_matchcentre_keys():
    """#1483: managers, codes, status and weather come from real source keys."""

    row = parse_match_html(_html(1946345), scope=SCOPE, game_id=1946345).matches.rows[0]

    assert row["home_manager"] == "Vincent Kompany"
    assert row["away_manager"] == "Enzo Maresca"
    assert row["status_code"] == 6
    assert row["period_code"] == 7
    assert row["status"] == "FT"
    assert row["weather"] is None
    shootout = parse_match_html(_html(1952492), scope=SCOPE, game_id=1952492)
    assert shootout.matches.rows[0]["status"] == "PEN"


def test_substitutions_carry_the_replaced_player():
    """#1483: both rows of a substitution pair name the other player."""

    rows = parse_match_html(
        _html(1946345), scope=SCOPE, game_id=1946345
    ).substitutions.rows
    by_key = {(row["player_id"], row["action"]): row for row in rows}

    assert by_key[(370912, "on")]["related_player_id"] == 134946
    assert by_key[(134946, "off")]["related_player_id"] == 370912
    assert len(rows) == 16
    assert all(row["related_player_id"] is not None for row in rows)
    pairs = {
        frozenset((row["player_id"], row["related_player_id"])) for row in rows
    }
    assert len(pairs) == 8


def test_event_type_dictionary_is_extracted_from_the_match_page():
    """#1483: the sibling matchCentreEventTypeJson map (219 name -> code)."""

    result = parse_match_html(_html(1946345), scope=SCOPE, game_id=1946345)

    assert len(result.event_types) == 219
    assert result.event_types["shotSixYardBox"] == 0
    assert result.event_types["pos"] == 218
    assert len(result.datasets) == 7
    assert extract_matchcentre_event_types("<html>no dictionary</html>") is None


def _profile_html() -> str:
    return (FIXTURES / "profile-370912-characteristics.html").read_text(
        encoding="utf-8"
    )


def test_profile_characteristics_are_parsed_from_the_character_card():
    rows = parse_profile_bundle(_profile_html(), player_id=370912).characteristics.rows

    strengths = [
        (row["name"], row["level"], row["category"], row["position"])
        for row in rows
        if row["kind"] == "strength"
    ]
    assert strengths == [
        ("Passing", "Very Strong", "Offensive", 1),
        ("Aerial Duels", "Strong", "Offensive", 2),
        ("Ball interception", "Strong", "Defensive", 3),
    ]
    assert rows[0]["level_class"] == "level55"
    assert not [row for row in rows if row["kind"] == "weakness"]
    styles = [row for row in rows if row["kind"] == "style"]
    assert [(row["name"], row["level"], row["level_class"]) for row in styles] == [
        ("Likes to play short passes", None, None)
    ]


def test_profile_without_character_card_has_no_characteristics():
    html = _profile_html()
    html = html[: html.index('<div class="sws-content character-card')] + "</body></html>"

    parsed = parse_profile_bundle(html, player_id=370912)

    assert parsed.characteristics.rows == ()
    assert parsed.profiles.rows[0]["name"] == "Kim Min-Jae"
