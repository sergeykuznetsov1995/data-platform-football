#!/bin/bash
# Автомат доставки FotMob B6: в окно между волнами сам ставит master в боевое
# дерево, принимает результат, при любой поломке ОТКАТЫВАЕТ и докладывает в TG.
# Заведён 25.08 решением владельца: за 20–24.08 пять окон подряд упущены, потому
# что доставка была привязана к живой сессии (урок 111). Сигнал (TG-алерт) работал
# оба последних вечера — не работало нажатие кнопки.
#
# Cron: */5 * * * * <каталог установки>/auto_deliver.sh  (окно и одноразовость — внутри)
# Пути машины и пины выката — из env-файла контура (deploy/fotmob/fotmob.env.example,
# #1155 этап 3): «поднять пин» = переписать FOTMOB_TARGET/FOTMOB_ROLLBACK_*/
# FOTMOB_NEW_CODE_* в env-файле атомарно (write + mv), скрипт не правится.
#
# Обёртка НЕ дублирует логику доставки: всю работу делает отрепетированный
# b6_deliver.sh apply из того же каталога (проверки окна/дерева, checkout, приёмка
# метабазой, сьют). Обёртка добавляет то, чего у него нет: crash-safe состояние,
# автооткат с проверкой результата, доказательство приёмки, отчёт в Telegram и
# запуск кампании истории.
#
# Правки после ревью Sol 25.08 (раунд 1, вердикт «переделать»):
#   * маркер inflight — смерть автомата между checkout и приёмкой больше не
#     выглядит как успешная доставка;
#   * откат проверяется по факту (SHA + чистота дерева + import_error), а не
#     объявляется выполненным;
#   * приёмка подтверждается появлением dag_collect_fotmob_players — DAG есть
#     только в новом коде, поэтому import_error=0 сам по себе больше не считается
#     доказательством, что дерево перечитано;
#   * запуск кампании отделён от доставки своим маркером и повторяется, если
#     драйвер не поднялся;
#   * чёрный ход FORCE_WINDOW убран: окно не проверяется только тогда, когда
#     TREE физически не боевое дерево (сравнение канонизированных путей).
#
# Три правила, к которым свелась логика решений (ревью Sol, раунды 8–10):
#   1. У боевого дерева ровно два законных состояния, и ОБА ЧИСТЫЕ: откатное и
#      принятое. Любое иное — руки НЕМЕДЛЕННО (кампанию гасим, ставим выключатель),
#      не дожидаясь окна: иначе чужой коммит живёт в бою до 20 часов.
#   2. Право на `checkout -f` даёт ТОЛЬКО дерево, стоящее на цели: это
#      единственное доказательство, что переключали мы. Во всех прочих случаях
#      автомат зовёт руки, а бой остаётся на принятом откатном коде. И ещё одно
#      условие: кампания должна быть ОСТАНОВЛЕНА подтверждённо — менять файлы под
#      живым писателем нельзя, он читает дерево на ходу (ревью Sol, раунд 17).
#      Бой остаётся на непринятом коде, но новых повреждений автомат не создаёт.
#   3. Откат не уничтожает работу: перед каждым `checkout -f` правки отслеживаемых
#      файлов сохраняются в патч, и его имя идёт в алерт.
# И ни один исход не теряется: неудачная отправка в Telegram кладёт текст в
# очередь, которую дожимает первым делом каждый следующий тик cron; если недоступна
# и очередь — автомат глушит сам себя, чтобы не действовать молча.
set -u
export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin

# Env-файл контура читается как compose (ключи FOTMOB_*, без подстановок и без
# export — см. env.sh). Нет файла — автомат не делает НИЧЕГО: без него неизвестны ни
# дерево, ни каталог состояния, ни пины, а cron-лог получает причину в stderr.
HERE=$(dirname "$(readlink -f "$0")")
ENV_FILE="${FOTMOB_ENV_FILE:-/etc/data-platform/fotmob.env}"
# shellcheck source=deploy/fotmob/env.sh
. "$HERE/env.sh"
fotmob_load_env "$ENV_FILE" || exit 2
export FOTMOB_ENV_FILE="$ENV_FILE"   # тот же файл читает b6_deliver.sh, которого мы зовём

PROD_TREE=${FOTMOB_RELEASE_ROOT:?FOTMOB_RELEASE_ROOT не задан в env-файле}
TREE=$(realpath -m "${TREE:-$PROD_TREE}")
IS_PROD=$([ "$TREE" = "$(realpath -m "$PROD_TREE")" ] && echo 1 || echo 0)

TARGET=${FOTMOB_TARGET:?FOTMOB_TARGET не задан в env-файле}                   # цель выката
ROLLBACK_REF=${FOTMOB_ROLLBACK_REF:?FOTMOB_ROLLBACK_REF не задан в env-файле} # прежний боевой HEAD; голый SHA:
ROLLBACK_SHA=${FOTMOB_ROLLBACK_SHA:?FOTMOB_ROLLBACK_SHA не задан в env-файле} # ветка deploy/fotmob-b6-master при apply переезжает на цель
# Пины сравниваются с `git rev-parse --short HEAD` по префиксу (head_of/on_target):
# полный 40-значный SHA не совпал бы никогда, и исправное дерево считалось бы
# незаконным (кампания стоп, выключатель). Поэтому только короткая форма — 7–8 hex,
# как печатает `git rev-parse --short` (ревью Sol, #1155 этап 3).
for pin in TARGET ROLLBACK_SHA; do
  case "${!pin}" in
    ???????|????????) case "${!pin}" in *[!0-9a-f]*) ;; *) continue ;; esac ;;
  esac
  echo "FOTMOB_$pin='${!pin}': ожидается короткий SHA (7–8 hex, как git rev-parse --short)" >&2
  exit 2
done
# Доказательство доставки — целевой md5 модуля, который меняет цель, в контейнере
# (bind-mount цел, checkout дошёл) плюс живой контур: есть даг, перечитанный
# планировщиком за окно свежести, и ноль ошибок импорта. Появление нового дага
# доказательством быть не может: даг, попавший в бой прошлой доставкой, «виден» ещё
# ДО следующей. Пара файл/md5 — пин из env-файла; переопределяется лишь для
# репетиции (обе ветки: доказательство есть / его нет).
NEW_CODE_FILE=${NEW_CODE_FILE:-${FOTMOB_NEW_CODE_FILE:?FOTMOB_NEW_CODE_FILE не задан в env-файле}}
NEW_CODE_MD5=${NEW_CODE_MD5:-${FOTMOB_NEW_CODE_MD5:?FOTMOB_NEW_CODE_MD5 не задан в env-файле}}
DELIVER=${DELIVER:-$HERE/b6_deliver.sh}
CAMPAIGN=${CAMPAIGN:-${FOTMOB_CAMPAIGN_DIR:?FOTMOB_CAMPAIGN_DIR не задан в env-файле}}
LOG=${LOG:-${FOTMOB_LOG:?FOTMOB_LOG не задан в env-файле}}
STATE=${STATE:-${FOTMOB_STATE_DIR:?FOTMOB_STATE_DIR не задан в env-файле}}
LOCK=${LOCK:-$STATE/fotmob-auto-deliver.lock}
INFLIGHT=$STATE/fotmob-b6-inflight
PENDING=$STATE/fotmob-pending-alert       # недоставленные алерты, дожимаются каждым тиком
CAMPAIGN_STARTED=$STATE/fotmob-campaign-started
ACCEPTED=$STATE/fotmob-b6-accepted             # SHA кода, приёмку которого подтвердили
STARTFAILS=$STATE/fotmob-campaign-start-fails  # подряд неудачных запусков драйвера
START_FAILS_MAX=${START_FAILS_MAX:-3}          # после стольких попыток автомат глушится
ATTEMPTED=$STATE/fotmob-auto-deliver-attempted-$(date -u +%F)
OFF=$STATE/fotmob-auto-deliver.off            # выключатель: ставит человек или сам автомат
DELIVER_TIMEOUT=${DELIVER_TIMEOUT:-900}       # 90 с ожидания приёмки + сьют укладываются с запасом
TG_ENV=${TG_ENV:-${FOTMOB_TG_ENV:?FOTMOB_TG_ENV не задан в env-файле}}   # файл с токеном/чатом Telegram
METADB=${METADB:-${FOTMOB_METADB_CONTAINER:?FOTMOB_METADB_CONTAINER не задан в env-файле}}
CAMPAIGN_CONTAINER=${CAMPAIGN_CONTAINER:-${FOTMOB_SCHEDULER_CONTAINER:?FOTMOB_SCHEDULER_CONTAINER не задан в env-файле}}
# Признак писателя волны. Вынесен в переменную только ради репетиций: стенд
# гоняет сценарии на копии дерева, а pgrep смотрит на весь хост и видел бы
# НАСТОЯЩУЮ идущую волну, из-за чего репетиция отката краснела бы не по делу.
WRITER_PAT=${WRITER_PAT:-'dags/scripts/run_fotmob_scrape[r].py'}

# Каталог состояния НЕ создаём молча. `mkdir -p` здесь означал, что потеря каталога
# незаметна: вместе с ним исчезают маркер незакрытой доставки и защёлка суток, и
# дерево, стоящее на цели, становится неотличимо от доставленного и ПРИНЯТОГО —
# автомат поднял бы кампанию на коде, приёмку которого никто не подтверждал
# (ревью Sol, раунд 27). Само отсутствие проверяется ниже, вместе с подменой.
RESCUE_NOTE=""
STOP_NOTE=""
log(){
  # В подменённый лог не пишем: перенаправление пошло бы ПО ссылке, а целью может
  # оказаться файл боевого дерева — автомат сам испортил бы дерево ещё до доставки
  # (ревью Sol, раунд 22). Немыми не остаёмся: строка уходит в поток ошибок, то
  # есть в cron-лог.
  if [ -L "$LOG" ] || { [ -e "$LOG" ] && [ ! -f "$LOG" ]; }; then
    echo "$(date -u +%FT%TZ) [лог подменён] $*" >&2
    return 0
  fi
  echo "$(date -u +%FT%TZ) $*" >> "$LOG"
}
# Маркер обязан быть ВИДЕН как обычный файл, а не просто «запись прошла успешно».
# Symlink на /dev/null принимает запись и отдаёт нулевой код, но `-f` его не видит:
# INFLIGHT считался бы созданным, а следующий тик не нашёл бы маркера и принял
# непринятое дерево за успешно доставленное (ревью Sol, раунд 16). Каталог на
# месте маркера ловился и раньше — на нём падает само перенаправление.
# `-f` идёт по symlink, поэтому «обычный файл» проверяется вместе с `! -L`:
# symlink на любой существующий файл иначе признавался бы настоящим маркером, и
# подменённая защёлка молча отменяла бы доставку, а подменённый `.off` — молча
# глушил автомат (ревью Sol, раунд 19).
is_plain(){ [ -f "$1" ] && [ ! -L "$1" ]; }
# «Не обычный файл» и «ничего нет» — разные новости, а is_plain отвечает на обе
# одинаково: «нет». Там, где отсутствие маркера что-то РАЗРЕШАЕТ (принять дерево
# без приёмки, считать очередь алертов пустой), подмена молча выдавала себя за
# чистое место (ревью Sol, раунд 20). Битую ссылку `-e` не видит — отсюда `-L`.
odd_path(){ { [ -e "$1" ] || [ -L "$1" ]; } && ! is_plain "$1"; }
mk_marker(){
  # Проверяем ДО записи: перенаправление идёт ПО ссылке и обнуляет её цель, а
  # целью может оказаться файл боевого дерева — автомат сам сделал бы дерево
  # грязным, то есть выбил бы его из законных состояний (ревью Sol, раунд 20).
  if odd_path "$1"; then
    log "на месте $1 не обычный файл — не пишу туда ничего"
    return 1
  fi
  { : > "$1"; } 2>/dev/null && is_plain "$1"
}
# Отметки «уже сказал за сегодня» — та же мина, что и маркеры, только наизнанку:
# подменённая на symlink отметка `-e`-проверкой выглядит поставленной и глушит
# сообщение до конца суток, хотя оно никогда не уходило (ревью Sol, раунд 17).
# Действительной считается только отметка, которая ЕСТЬ как обычный файл; если её
# не удалось поставить — сообщение просто повторится следующим тиком, и это лучше
# немоты.
said_today(){ is_plain "$1"; }
mark_said(){ mk_marker "$1" || log "не смог поставить отметку $1 — сообщение повторится следующим заходом"; }
# Выключатель ставим тоже с проверкой: незаписанный OFF означает, что следующий
# тик пойдёт работать дальше, и об этом должен остаться след в логе.
set_off(){ mk_marker "$OFF" || log "ВЫКЛЮЧАТЕЛЬ $OFF НЕ ЗАПИСАН — следующий тик не остановится"; }
# Отправляем сами и проверяем ответ API: штатный хук tg-send.sh выходит нулём и
# при отсутствии настроек, и при упавшем curl, поэтому подтверждением доставки
# служить не может (ревью Sol, раунд 7). Успех — только «ok":true» от Telegram.
tg(){
  local text="$*" resp env_file="$TG_ENV"
  if [ ! -f "$env_file" ]; then
    log "АЛЕРТ НЕ ДОСТАВЛЕН (нет $env_file): $text"; return 1
  fi
  # shellcheck disable=SC1090
  . "$env_file"
  if [ -z "${TELEGRAM_BOT_TOKEN:-}" ] || [ -z "${TELEGRAM_CHAT_ID:-}" ]; then
    log "АЛЕРТ НЕ ДОСТАВЛЕН (нет токена/чата): $text"; return 1
  fi
  resp=$(curl -s --max-time 15 "https://api.telegram.org/bot${TELEGRAM_BOT_TOKEN}/sendMessage" \
    -d chat_id="${TELEGRAM_CHAT_ID}" --data-urlencode text="[$(hostname)] ${text}" 2>/dev/null)
  case "$resp" in *'"ok":true'*) return 0 ;; esac
  log "АЛЕРТ НЕ ДОСТАВЛЕН (ответ: $(printf '%s' "$resp" | head -c 200)): $text"
  return 1
}
# Закрывающие сообщения терять нельзя: раньше результат tg() игнорировался, и при
# недоступном Telegram после подтверждённого отката (или предполётного отказа) не
# оставалось ни алерта, ни выключателя, а суточная защёлка глушила автомат до
# завтра — исход был известен только логу (ревью Sol, раунд 9). Теперь неудачная
# отправка кладёт текст в очередь, и её дожимает каждый следующий тик cron.
#
# Возвращает 0, если сообщение ДОСТАВЛЕНО ИЛИ ГАРАНТИРОВАННО БУДЕТ доставлено —
# только на этом основании вызывающий вправе ставить суточные маркеры «уже сказал»
# и снимать INFLIGHT. Запись в очередь тоже может не удаться (нет места, каталог
# недоступен), и раньше это оставалось незамеченным: вызывающие вели себя так,
# будто сказали (ревью Sol, раунд 10).
tg_durable(){
  tg "$@" && return 0
  # Фигурные скобки обязательны: сообщение о неудачной ПЕРЕНАПРАВЛЕНИИ печатает сам
  # bash, и `2>/dev/null` на самой команде его не глушит — в cron-лог сыпался мусор.
  # Мало записать — очередь должна ОТДАВАТЬ записанное обратно: symlink на
  # /dev/null принимает строку с нулевым кодом и всегда читается пустым, а
  # flush_pending работает по `-f` и такой очереди не увидит вовсе. Раньше это
  # означало бы «алерт отложен» при потерянном алерте (ревью Sol, раунд 16).
  # Проверка ДО записи: раньше строка уже уходила ПО ссылке, и только потом
  # выяснялось, что очередь подменена (ревью Sol, раунд 22).
  if ! odd_path "$PENDING" \
     && { printf '%s\n' "$*" >> "$PENDING"; } 2>/dev/null \
     && is_plain "$PENDING" && grep -qxF -e "$*" "$PENDING" 2>/dev/null; then
    log "алерт отложен в очередь ($PENDING) — дожму следующим заходом"
    return 0
  fi
  # Ни канала, ни очереди: сказать нечем. Дальше идти нельзя — иначе автомат
  # продолжит действовать (вплоть до запуска драйвера) после потерянного алерта,
  # а вызывающие всё равно не проверяли код возврата (ревью Sol, раунд 11).
  # Поэтому функция НЕ возвращает неудачу: она завершает работу целиком.
  log "АЛЕРТ ПОТЕРЯН (ни Telegram, ни очередь $PENDING недоступны): $*"
  # Кампанию гасим ТОЖЕ: заглушить себя мало, если драйвер уже поднят — он
  # переживает и выключатель, и смерть автомата, а следующие тики выйдут по .off
  # и до него не дойдут. Онемевший автомат не должен оставлять за собой
  # работающего писателя (ревью Sol, раунд 14).
  stop_campaign
  set_off
  exit 1
}
flush_pending(){
  # Подменённая очередь (symlink, каталог) — не «пусто»: накопленные алерты в ней
  # уже не прочитать, а новые складывать некуда, и раньше автомат просто шёл
  # работать дальше — без сообщения и без выключателя (ревью Sol, раунд 20).
  # Говорим НАПРЯМУЮ: durable-путь писал бы в ту же нерассылаемую очередь.
  if odd_path "$PENDING"; then
    log "ОЧЕРЕДЬ АЛЕРТОВ ПОДМЕНЕНА ($PENDING — не обычный файл): отложенное не рассылается, новое складывать некуда; глушу автомат"
    tg "🆘 FotMob: на месте очереди алертов ($PENDING) не обычный файл — отложенные сообщения потеряны, новые складывать некуда. Кампанию останавливаю, автомат глушу: снять $OFF после разбора. Лог: $LOG"
    stop_campaign
    set_off
    exit 1
  fi
  # Именно -f: если на месте очереди окажется каталог, `-s` даёт истину, и цикл
  # уходит читать каталог с руганью в cron-лог.
  { is_plain "$PENDING" && [ -s "$PENDING" ]; } || return 0
  local line kept="$PENDING.kept" failed=0
  # Через mk_marker: подменённый на symlink `.kept` принимал бы и создание, и все
  # записи, а читался бы пустым — очередь стёрлась бы вместе с недоставленными
  # алертами, и автомат пошёл бы работать дальше как ни в чём не бывало (ревью
  # Sol, раунд 17). Основную очередь это не портит: не смогли — разберём позже.
  if ! mk_marker "$kept"; then
    # Очередь цела — ничего не потеряно, но и не рассылается. Молчать об этом
    # нельзя: подменённый навсегда `.kept` означал бы вечно непрочитанную очередь.
    # Шлём напрямую (durable-путь писал бы в ту же нерассылаемую очередь) и не
    # чаще раза в сутки; не ушло — отметка не ставится, повторим следующим тиком.
    log "не могу создать $kept — очередь оставляю как есть, разберу позже"
    local m="$STATE/fotmob-kept-broken-$(date -u +%F)"
    if ! said_today "$m"; then
      tg "🆘 FotMob: не могу разобрать очередь отложенных алертов ($kept не создаётся). Сообщения целы, но не рассылаются. НУЖНЫ РУКИ. Лог: $LOG" && mark_said "$m"
    fi
    return 0
  fi
  while IFS= read -r line; do
    [ -n "$line" ] || continue
    tg "$line" && continue
    # Если недоставленную строку не удалось перенести, пустой $kept выглядел бы
    # как «всё разослано», и очередь стиралась вместе с алертом (ревью Sol,
    # раунд 11). Ошибку запоминаем и очередь НЕ трогаем. Перенос считается
    # удавшимся, только если строка ЧИТАЕТСЯ обратно — тот же принцип, что и в
    # tg_durable (ревью Sol, раунд 17).
    if ! { { printf '%s\n' "$line" >> "$kept"; } 2>/dev/null \
           && grep -qxF -e "$line" "$kept" 2>/dev/null; }; then
      failed=1
    fi
  done < "$PENDING"
  if [ "$failed" = 1 ]; then
    log "АЛЕРТ ПОТЕРЯН при разборе очереди: не могу переписать $PENDING — оставляю очередь как есть"
    rm -f "$kept" 2>/dev/null
    # Тот же инвариант, что и в tg_durable: онемевший автомат не оставляет за собой
    # работающего писателя (ревью Sol, раунд 15).
    stop_campaign
    set_off
    exit 1
  fi
  if [ -s "$kept" ]; then
    mv -f "$kept" "$PENDING" 2>/dev/null || { log "не могу заменить $PENDING — очередь оставляю как есть"; rm -f "$kept" 2>/dev/null; }
  else
    rm -f "$kept" "$PENDING" 2>/dev/null
    log "очередь отложенных алертов разобрана"
  fi
}
# Замок сломан — значит, вероятно, сломан и каталог состояния, где лежит очередь.
# Поэтому шлём напрямую, а суточную отметку ставим ТОЛЬКО по доставленному
# сообщению: иначе неотправленный алерт пометился бы как сказанный и автомат
# молчал бы сутки (ревью Sol, раунд 12). Не доставили — повторим следующим тиком.
lock_alert(){
  local mark="$STATE/fotmob-lock-broken-$(date -u +%F)"
  log "НЕ МОГУ ВЗЯТЬ ЗАМОК: $1 — автомат не работает"
  said_today "$mark" && return 0
  if tg "🆘 FotMob: автомат не может взять свой замок ($1) — доставки НЕ БУДЕТ. НУЖНЫ РУКИ. Лог: $LOG"; then
    mark_said "$mark"
  fi
}
head_of(){ git -C "$TREE" rev-parse --short HEAD 2>/dev/null || echo "?"; }
# Дерево стоит на принятом коде? Это единственное состояние, при котором автомат
# имеет право на `checkout -f`: только оно доказывает, что переключали МЫ.
on_target(){ case "$(head_of)" in "$TARGET"*) return 0 ;; esac; return 1; }
# timeout обязателен: зависший docker exec/psql держал бы flock и оставил дерево на
# непринятом коде без единого сообщения (ревью Sol, раунд 3).
metadb(){
  local out
  # Код возврата берём у docker exec, а не у хвоста конвейера: с `| tr` статус
  # всегда нулевой, и мёртвая метабаза возвращала бы пустую строку вместо X.
  if ! out=$(timeout -k 5 "${METADB_TIMEOUT:-30}" docker exec "$METADB" psql -U airflow -d airflow -tA -c "$1" 2>/dev/null); then
    echo X; return
  fi
  printf '%s' "$out" | tr -d ' \r'
}
# Доказательство приёмки — не «дерево на нужном SHA», а целевой модуль, ВИДИМЫЙ из
# контейнера (приметой служит md5 файла из пина FOTMOB_NEW_CODE_*), плюс живой
# контур: fotmob-даг, перечитанный планировщиком за окно свежести, и ноль ошибок
# импорта. Отвечает 1 (принято), 0 (не принято) или X (проверить нечем —
# вслепую не решаем; сюда же попадает лежащий контейнер).
acceptance_seen(){ # $1 = сколько минут свежести перечитывания требуем (по умолчанию 15)
  local md5 dags errs
  md5=$({ timeout -k 5 "${METADB_TIMEOUT:-30}" docker exec "$CAMPAIGN_CONTAINER" md5sum "$NEW_CODE_FILE" 2>/dev/null | cut -d' ' -f1; } || true)
  [ -n "$md5" ] || { echo X; return; }
  [ "$md5" = "$NEW_CODE_MD5" ] || { echo 0; return; }
  dags=$(metadb "SELECT count(*) FROM dag WHERE dag_id LIKE '%fotmob%' AND is_active AND last_parsed_time > now() - interval '${1:-15} minutes';")
  errs=$(metadb "SELECT count(*) FROM import_error;")
  case "$dags$errs" in *X*) echo X; return ;; esac
  if [ "$errs" = 0 ] && [ "$dags" -gt 0 ] 2>/dev/null; then echo 1; else echo 0; fi
}
# Приёмка живёт дольше одного запуска: раньше её след существовал ровно до конца
# доставки (успех лишь СНИМАЛ маркер незакрытой доставки), и дерево на цели без
# маркеров выглядело принятым — потери каталога состояния хватало, чтобы автомат
# поднял кампанию на коде, приёмку которого никто не подтверждал (ревью Sol,
# раунд 28). Теперь принятый SHA записан, и «доставлено» проверяется по нему.
put_accepted(){ # $1 = SHA
  if odd_path "$ACCEPTED"; then
    log "на месте маркера приёмки $ACCEPTED не обычный файл — не пишу туда ничего"
    return 1
  fi
  { printf '%s\n' "$1" > "$ACCEPTED"; } 2>/dev/null && is_plain "$ACCEPTED"
}
read_accepted(){ is_plain "$ACCEPTED" && { head -c 64 "$ACCEPTED" 2>/dev/null | tr -d ' \n\r'; }; }
# «Чисто» должно означать проверенное «чисто», а не молчание сломанного git:
# при ошибке возвращаем X, и вызывающий трактует это как «не подтверждено».
# Считаем ТОЛЬКО отслеживаемые изменения: `checkout -f` возвращает именно их, а
# untracked-файл (случайный артефакт рядом с дагами) иначе навсегда заблокировал
# бы автомат «неподтверждённым откатом». Про untracked сообщаем отдельно.
dirty_of(){
  local st
  if ! st=$(git -C "$TREE" status --porcelain --untracked-files=no 2>/dev/null); then echo X; return; fi
  printf '%s' "$st" | grep -c . || true
}
# Неотслеживаемый файл в dags/ — это УЖЕ исполняемый непринятый код: Airflow
# читает каталог, а не индекс git. Из dirty_of() untracked исключены намеренно
# (иначе случайный артефакт навсегда заблокировал бы подтверждение отката,
# раунд 4), поэтому проверяем их отдельно и ровно там, где они исполняются
# (ревью Sol, раунд 11). В боевом дереве их ноль — проверено 25.08.
untracked_dags(){
  local st
  # БЕЗ --exclude-standard: .gitignore прячет и исполняемый код. В этом репозитории
  # он унаследовал джанговское правило `local_settings.py` (.gitignore:60), так что
  # dags/local_settings.py был бы невидим для git и при этом исполнялся: контейнер
  # монтирует dags/ целиком, а .airflowignore этого имени не знает (ревью Sol,
  # раунд 12). Отсеиваем только заведомо неисполняемый мусор интерпретатора —
  # в боевом дереве после такого фильтра остаётся 0 (проверено 25.08).
  if ! st=$(git -C "$TREE" ls-files --others -- dags 2>/dev/null); then echo X; return; fi
  printf '%s' "$st" | grep -vE '(^|/)__pycache__/|\.pyc$' | grep -c . || true
}
untracked_of(){
  local st
  if ! st=$(git -C "$TREE" ls-files --others --exclude-standard 2>/dev/null); then echo X; return; fi
  printf '%s' "$st" | grep -c . || true
}
# Перед откатом писателей быть не должно: и раннер волны, и юнит кампании читают
# файлы дерева на ходу. Ждём до WRITER_WAIT секунд, дальше откатываем всё равно —
# оставить бой на непринятом коде хуже, — но говорим об этом в алерте.
# Снять флаг мало: драйвер проверяет его только между юнитами, а юнит живёт до
# 30 минут и читает файлы дерева на ходу. Поэтому STOP + SIGTERM самому драйверу
# (ревью Sol, раунд 3). Идущий docker exec доработает, но нового юнита не будет.
# Маркер «кампания запущена» — вход во ВСЕ проверки её здоровья (пульс, состояние
# disabled, смерть драйвера). Если его не записать, эти проверки обходятся навсегда,
# а автомат сообщал бы только в локальный лог (ревью Sol, раунд 14).
mark_started(){
  mk_marker "$CAMPAIGN_STARTED" && return 0
  # Драйвер к этому моменту уже жив в обоих вызывающих путях. Оставить его без
  # наблюдения и просто заглушиться — это «зелёное, но пустое»: следующие тики
  # выйдут по выключателю, а писатель продолжит работу (ревью Sol, раунд 15).
  stop_campaign
  log "НЕ МОГУ СОЗДАТЬ $CAMPAIGN_STARTED — наблюдение не работает, кампания остановлена"
  tg_durable "🆘 FotMob: не могу создать маркер $CAMPAIGN_STARTED — за кампанией некому следить. НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора."
  set_off
  exit 1
}
# Признак юнита кампании: run-id вида fotmob-hist- носят только её процессы,
# раннеры волн — нет. Паттерн собран из двух кусков, чтобы pgrep не поймал сам
# себя через командную строку вызывающего шелла (наступало дважды за 25.08).
UNIT_PAT='run-id fotmob''-hist-'
# Юнит живёт ОТДЕЛЬНЫМ процессом внутри контейнера. Хост видит процессы
# контейнеров (проверено 25.08: `ps --ppid` показывает питона scheduler'а), но
# одного взгляда мало — спрашиваем и сам контейнер: недоступный docker не должен
# выдавать живого писателя за мёртвого.
driver_alive(){ pgrep -f "$CAMPAIGN/driver.sh" >/dev/null 2>&1; }
unit_alive(){
  pgrep -f "$UNIT_PAT" >/dev/null 2>&1 && return 0
  timeout -k 5 20 docker exec "$CAMPAIGN_CONTAINER" pgrep -f "$UNIT_PAT" >/dev/null 2>&1
}
# Возвращает 0 только при ПОДТВЕРЖДЁННОЙ остановке: ни драйвера, ни юнита. Раньше
# код `docker exec … pkill` игнорировался целиком, TERM ничем не дополнялся, и
# через 120 секунд ожидания автомат всё равно шёл в `checkout -f` — под живым
# писателем, который читает файлы смонтированного дерева на ходу (ревью Sol,
# раунд 16). Неподтверждённую остановку вызывающие обязаны отработать как аномалию:
# STOP_NOTE — готовый кусок текста для алерта.
stop_campaign(){
  STOP_NOTE=""
  # Каталог кампании может быть уже признан недоверенным (ссылка или его нет) — и
  # тогда её файлы трогать нельзя: `rm` и `STOP` ушли бы в цель ссылки. Сигналы
  # файлов не касаются, поэтому процессы останавливаем в любом случае: онемевший
  # автомат не должен оставлять за собой живого писателя (ревью Sol, раунд 26).
  local files_ok=1 d
  for d in "$CAMPAIGN/state" "$CAMPAIGN/logs"; do
    { [ -L "$d" ] || [ ! -d "$d" ]; } && files_ok=0
  done
  [ "$files_ok" = 1 ] || log "каталог кампании недоверен — останавливаю одними сигналами, файлов кампании не трогаю"
  # Ранний выход учитывает и живой юнит: после первого вызова campaign_enabled уже
  # снят, а юнит в контейнере мог остаться — повторный вызов обязан его добить.
  [ -f "$CAMPAIGN/state/campaign_enabled" ] || driver_alive || unit_alive || return 0
  if [ "$files_ok" = 1 ]; then
    rm -f "$CAMPAIGN/state/campaign_enabled" "$CAMPAIGN_STARTED"
  else
    rm -f "$CAMPAIGN_STARTED"
  fi
  # Через mk_marker: перенаправление пошло бы ПО ссылке и обнулило её цель, а сам
  # STOP остался бы несозданным — драйвер его не увидит (ревью Sol, раунд 20).
  # Остановку это не срывает: она в любом случае подтверждается сигналами и
  # опросом процессов, STOP лишь бережёт от рестарта.
  [ "$files_ok" = 1 ] && { mk_marker "$CAMPAIGN/state/STOP" || log "не смог поставить $CAMPAIGN/state/STOP — останавливаю кампанию одними сигналами"; }
  pkill -TERM -f "$CAMPAIGN/driver.sh" >/dev/null 2>&1 || true
  # Бьём юнит с обеих сторон: изнутри контейнера и с хоста (он видит те же
  # процессы) — так остановка не зависит от одного канала.
  timeout -k 5 30 docker exec "$CAMPAIGN_CONTAINER" pkill -TERM -f "$UNIT_PAT" >/dev/null 2>&1 || true
  pkill -TERM -f "$UNIT_PAT" >/dev/null 2>&1 || true
  local left=${STOP_WAIT:-60}
  while [ "$left" -gt 0 ] && { unit_alive || driver_alive; }; do sleep 5; left=$((left-5)); done
  if unit_alive || driver_alive; then
    log "кампания пережила TERM — добиваю KILL"
    timeout -k 5 30 docker exec "$CAMPAIGN_CONTAINER" pkill -KILL -f "$UNIT_PAT" >/dev/null 2>&1 || true
    pkill -KILL -f "$UNIT_PAT" >/dev/null 2>&1 || true
    pkill -KILL -f "$CAMPAIGN/driver.sh" >/dev/null 2>&1 || true
    left=${STOP_KILL_WAIT:-20}
    while [ "$left" -gt 0 ] && { unit_alive || driver_alive; }; do sleep 5; left=$((left-5)); done
  fi
  if unit_alive || driver_alive; then
    STOP_NOTE=" ВНИМАНИЕ: остановка кампании НЕ подтверждена (жив драйвер: $(driver_alive && echo да || echo нет), жив юнит: $(unit_alive && echo да || echo нет)) — писатель мог работать во время отката."
    log "КАМПАНИЯ НЕ ОСТАНОВЛЕНА: пережила KILL (драйвер: $(driver_alive && echo да || echo нет), юнит: $(unit_alive && echo да || echo нет))"
    return 1
  fi
  log "кампания остановлена и остановка подтверждена (нет ни драйвера, ни юнита в контейнере)"
  return 0
}
# Откат подтверждён, только если сошлись ВСЕ три признака: HEAD на откатном SHA,
# дерево чисто и метабаза отвечает нулём ошибок импорта. Ошибки могут дочищаться
# минуту-две после возврата файлов — даём три попытки; X (метабаза недоступна)
# подтверждением не считается (ревью Sol, раунд 4).
confirm_rollback(){
  local back dirty err i u ud
  back=$(head_of); dirty=$(dirty_of)
  case "$back" in "$ROLLBACK_SHA"*) : ;; *) echo "HEAD=$back (не откатный)"; return 1 ;; esac
  [ "$dirty" = 0 ] || { echo "HEAD=$back, но правок отслеживаемых файлов: $dirty"; return 1; }
  # `checkout -f` не удаляет неотслеживаемые файлы, а в dags/ они ИСПОЛНЯЮТСЯ.
  # Без этой проверки откат объявлялся подтверждённым, маркер снимался, выключатель
  # не ставился — и непринятый даг оставался в бою как минимум до следующего тика
  # (ревью Sol, раунд 13).
  ud=$(untracked_dags); [ "$ud" = 0 ] || { echo "HEAD=$back, но в dags/ $ud посторонних файлов (их checkout -f не удаляет)"; return 1; }
  u=$(untracked_of); [ "$u" = 0 ] || log "после отката в дереве $u неотслеживаемых файлов вне dags/ (откату не мешают, но посмотреть стоит)"
  err=X
  for i in 1 2 3; do
    err=$(metadb "SELECT count(*) FROM import_error;")
    [ "$err" = 0 ] && { echo "HEAD=$back, дерево чисто, import_error=0"; return 0; }
    sleep "${ROLLBACK_ERR_WAIT:-60}"
  done
  echo "HEAD=$back, дерево чисто, но import_error=$err"
  return 1
}
# Перед любым `checkout -f` спасаем правки отслеживаемых файлов в патч. Откат
# обязателен — бой не должен остаться на непринятом коде, — но уничтожать чужую
# работу он не вправе: правка могла появиться уже ПОСЛЕ переключения, когда дерево
# стоит на цели и выглядит «нашим» (ревью Sol, раунд 10). Имя файла идёт в алерт.
# Ставит RESCUE_NOTE — готовый кусок текста для алерта. Три исхода различаются:
# спасать нечего, спасли (имя патча), правки БЫЛИ но спасти не вышло. Раньше
# последние два были неотличимы, и откат молча уничтожал работу (ревью Sol,
# раунд 11). --binary обязателен: без него патч не сохраняет содержимое
# отслеживаемых бинарников, а они в репозитории есть.
rescue_diff(){
  RESCUE_NOTE=""
  [ "$(dirty_of)" != 0 ] || return 0
  local out="$STATE/fotmob-rescued-$(date -u +%Y%m%dT%H%M%SZ).patch"
  if { git -C "$TREE" diff --binary HEAD > "$out"; } 2>/dev/null && [ -s "$out" ]; then
    RESCUE_NOTE=" Правки дерева спасены в $out."
    log "правки отслеживаемых файлов сохранены в $out"
  else
    rm -f "$out" 2>/dev/null
    RESCUE_NOTE=" ВНИМАНИЕ: правки в дереве БЫЛИ, но сохранить их не удалось — откат их уничтожил."
    log "ВНИМАНИЕ: правки есть, но патч не создан — откат их уничтожит"
  fi
}
wait_writers(){
  local left=${WRITER_WAIT:-120}
  # Проверяем ДО ожидания: WRITER_WAIT=0 означает «не ждать», а не «считать
  # занятым» — иначе при нулевом ожидании автомат объявлял бы писателя живым,
  # даже когда его нет.
  while :; do
    { pgrep -f "$WRITER_PAT" >/dev/null 2>&1; } || { echo ok; return; }
    [ "$left" -gt 0 ] || break
    sleep 10; left=$((left-10))
  done
  echo busy
}

# Собственный каталог состояния обязан быть настоящим каталогом: ссылка на его
# месте уводит РАЗОМ всё — замок, маркеры, очередь алертов, выключатель, — причём
# `exec 9>"$LOCK"` создал бы файл в цели ссылки ещё до всякой проверки дерева, то
# есть автомат сам мог бы оставить посторонний файл в `dags/` (ревью Sol, раунд 26).
# Ни выключателя, ни очереди в этом состоянии нет — они там же; поэтому говорим
# напрямую, а суточную защёлку кладём рядом с логом, вне подменённого каталога.
if [ -L "$STATE" ] || [ ! -d "$STATE" ]; then
  log "КАТАЛОГ СОСТОЯНИЯ $STATE НЕ НА МЕСТЕ (ссылка или не каталог) — не трогаю ничего"
  said="$(dirname "$LOG")/fotmob-state-broken-$(date -u +%F)"
  if ! is_plain "$said"; then
    # Через mk_marker: голое `: >` пошло бы ПО ссылке и обнулило её цель, а целью
    # может быть файл боевого дерева — автомат сам сделал бы дерево грязным, пока
    # рассказывает о чужой подмене (ревью Sol, раунд 27).
    tg "🆘 FotMob: каталог состояния автомата ($STATE) — ссылка или его нет. Замок, маркеры и очередь ушли бы в чужое место (вплоть до dags/). Автомат не делает НИЧЕГО и заглушить себя не может — выключатель лежит там же. НУЖНЫ РУКИ. Лог: $LOG" \
      && { mk_marker "$said" || true; }
  fi
  exit 1
fi

# Один экземпляр: доставка идёт 2–4 минуты, cron будит каждые 5.
# Ошибку открытия замка проверяем: если $LOCK стал каталогом или недоступен,
# flock получает битый дескриптор, и ветка «|| exit 0» молча выключала бы автомат
# на каждом тике — без алерта и без выключателя (ревью Sol, раунд 11).
# Проверяем ДО открытия: перенаправление идёт ПО ссылке и обнуляет её цель, а
# целью может оказаться файл боевого дерева — автомат сам сделал бы дерево
# грязным, и только следующий гейт заметил бы это, уже постфактум (ревью Sol,
# раунд 21). Каталог на месте замка ловился и раньше — на нём падает открытие.
if odd_path "$LOCK"; then
  log "НА МЕСТЕ ЗАМКА $LOCK НЕ ОБЫЧНЫЙ ФАЙЛ — не открываю его вовсе, глушу автомат"
  lock_alert "на месте замка $LOCK не обычный файл — открывать его нельзя (запись пошла бы по ссылке)"
  set_off
  exit 1
fi
if ! { exec 9>"$LOCK"; } 2>/dev/null; then
  lock_alert "не могу открыть замок $LOCK"
  exit 1
fi
# Не всякий ненулевой код flock — конкуренция. Ровно 1 означает «замок занят», и
# только он оправдывает молчаливый выход; любой другой код — поломка, о которой
# раньше не узнавал никто (ревью Sol, раунд 12).
flock -n 9; frc=$?
if [ "$frc" != 0 ]; then
  [ "$frc" = 1 ] && exit 0
  log "flock отказал кодом $frc — это не конкуренция"
  lock_alert "flock отказал кодом $frc (не конкуренция)"
  exit 1
fi

# ---- 0б. Каталоги кампании ----------------------------------------------------
# Проверка стоит раньше ВСЕГО, что трогает кампанию: `stop_campaign` удаляет в
# `state` файлы, ветки здоровья читают оттуда пульс и FAILED, а запуск драйвера
# открывает лог в `logs`. Подменённый на ссылку каталог уводит и чтения, и записи
# в чужое место, и проверки конечных путей этого не видят: у них цель ссылки
# выглядит обычным файлом (ревью Sol, раунды 24–25). Отсутствие каталога — тоже
# авария, а не «ещё не создали»: без него автомат не сможет ни поднять кампанию,
# ни оставить след, и повторял бы одну и ту же неудачу каждым тиком.
for d in "$CAMPAIGN/state" "$CAMPAIGN/logs"; do
  if [ -L "$d" ] || [ ! -d "$d" ]; then
    # Гасить кампанию тут нечем: остановка работает через файлы в том самом
    # каталоге, которому нельзя доверять. Поэтому просто говорим, жив ли писатель.
    alive=$( { driver_alive || unit_alive; } && echo "ДА, писатель ЖИВ" || echo "писателей нет")
    log "КАТАЛОГ КАМПАНИИ $d НЕ НА МЕСТЕ (ссылка или не каталог; $alive) — глушу автомат"
    tg_durable "🆘 FotMob: каталог кампании $d — ссылка или его нет на месте ($alive). Записи кампании ушли бы мимо, останавливать её через подменённый каталог нельзя. НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора. Лог: $LOG"
    set_off
    exit 1
  fi
done

# ---- 0в. Собственный лог ------------------------------------------------------
# Лог — не только запись о работе: в него перенаправляется ВЫВОД доставки
# (`"$DELIVER" apply >> "$LOG"`), поэтому подменённый путь означает, что чужой
# файл (вплоть до файла боевого дерева) будет исписан выводом b6 (ревью Sol,
# раунд 22). Работать в таком состоянии нельзя: говорим напрямую и глушимся.
if odd_path "$LOG"; then
  echo "$(date -u +%FT%TZ) НА МЕСТЕ ЛОГА $LOG НЕ ОБЫЧНЫЙ ФАЙЛ — глушу автомат" >&2
  tg "🆘 FotMob: на месте лога автомата ($LOG) не обычный файл — вывод доставки ушёл бы по ссылке в чужой файл. Ничего не делаю. НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора."
  stop_campaign
  set_off
  exit 1
fi

# ---- 0а. Недоставленные алерты ----------------------------------------------
# ДО выключателя: заглушенный автомат тем более обязан договорить то, что не смог
# сказать раньше.
flush_pending

# ---- 0. Выключатель --------------------------------------------------------
# Автомат сам ставит его, когда откат не подтверждён, а человек — когда откатил
# дерево руками: иначе следующий тик cron через 5 минут вернул бы забракованный
# код обратно. Снимается только руками.
if [ -e "$OFF" ] || [ -L "$OFF" ]; then
  # На месте выключателя может оказаться не файл, а symlink на /dev/null или
  # каталог. Стоять по такому «выключателю» автомат обязан (вдруг это всё-таки
  # чьё-то решение), но МОЛЧА стоять — нет: его никто не ставил, а бой мог
  # остаться на непринятом коде, и об этом не узнал бы никто (ревью Sol, раунд 18).
  if ! is_plain "$OFF" && ! said_today "$STATE/fotmob-off-broken-$(date -u +%F)"; then
    tg_durable "🆘 FotMob: на месте выключателя ($OFF) не обычный файл — автомат стоит, но это не чьё-то решение. Дерево: $(head_of). НУЖНЫ РУКИ. Лог: $LOG"
    mark_said "$STATE/fotmob-off-broken-$(date -u +%F)"
  fi
  # Молчать при незакрытой доставке нельзя: если автомат заглушился с деревом в
  # неизвестном состоянии, об этом надо напоминать — но не чаще раза в сутки
  # (ревью Sol, раунд 4).
  # Подменённый маркер тоже считается висящим: раз на его месте не обычный файл,
  # состояние прошлой доставки неизвестно ровно так же (ревью Sol, раунд 20).
  if { is_plain "$INFLIGHT" || odd_path "$INFLIGHT"; } && ! said_today "$STATE/fotmob-off-reminded-$(date -u +%F)"; then
    # Отметку можно ставить сразу: tg_durable либо отправил, либо поставил в
    # очередь, которую разбирает flush_pending выше (ревью Sol, раунды 5 и 9).
    tg_durable "🆘 FotMob: автомат заглушен ($OFF) и незакрытая доставка ещё висит ($INFLIGHT). Дерево: $(head_of). НУЖНЫ РУКИ."
    mark_said "$STATE/fotmob-off-reminded-$(date -u +%F)"
  fi
  exit 0
fi

# ---- 0б. Разбор прерванной доставки -----------------------------------------
# Маркер остаётся, только если прошлый запуск умер между checkout и завершением.
# Без него следующий cron увидел бы целевой HEAD и принял непроверенное дерево
# за успешно доставленное.
#
# Подмена на месте маркера — не «маркера нет»: is_plain отвечает «нет» и на
# symlink, и на каталог, после чего дерево на целевом коде объявлялось бы
# доставленным БЕЗ приёмки, а на непринятом коде поднималась бы кампания — молча
# (ревью Sol, раунд 20). Состояние прошлой доставки в таком случае неизвестно,
# и решать его вправе только руки.
if odd_path "$INFLIGHT"; then
  # Кампанию гасим первой и всегда: под ней может быть непринятый код.
  stop_campaign
  log "НА МЕСТЕ МАРКЕРА ДОСТАВКИ ($INFLIGHT) НЕ ОБЫЧНЫЙ ФАЙЛ — состояние прошлой доставки неизвестно, дерево не трогаю (HEAD=$(head_of)), глушу автомат"
  tg_durable "🆘 FotMob: на месте маркера доставки ($INFLIGHT) не обычный файл — понять, чем кончилась прошлая доставка, нельзя. Дерево (HEAD=$(head_of)) не трогаю, кампанию остановил.${STOP_NOTE} НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора. Лог: $LOG"
  set_off
  exit 1
fi
if is_plain "$INFLIGHT"; then
  h=$(head_of)
  # Кампания на непринятом коде недопустима — гасим первой в любом случае.
  stop_campaign
  # Не остановилась — дерево не трогаем вовсе: `checkout -f` под живым писателем
  # меняет файлы, которые он читает на ходу, и добавляет к одной беде вторую.
  # Бой остаётся на непринятом коде, зато без новых повреждений (ревью Sol, раунд 17).
  if [ -n "$STOP_NOTE" ]; then
    log "ПИСАТЕЛЬ КАМПАНИИ НЕ ОСТАНОВЛЕН — дерево не трогаю (HEAD=$h), глушу автомат"
    tg_durable "🆘 FotMob: прошлая доставка оборвалась (HEAD=$h), и остановить кампанию не удалось.${STOP_NOTE} Дерево НЕ откатываю: менять файлы под живым писателем нельзя. НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора. Лог: $LOG"
    set_off
    exit 1
  fi
  # Единственное доказательство «переключали МЫ» — дерево на целевом коде. Всё
  # прочее (третий коммит, правки поверх отката, нечитаемый HEAD) может оказаться
  # чужой работой, и `checkout -f` её бы уничтожил. Бой при этом стоит на принятом
  # откатном коде — терпимо; неизвестность разбирают руки (ревью Sol, раунд 9).
  if ! on_target; then
    log "МАРКЕР ПРЕРВАННОЙ ДОСТАВКИ, но дерево не на цели (HEAD=$h) — доказательства, что переключали мы, нет; глушу автомат"
    tg_durable "🆘 FotMob: прошлая доставка оборвалась, дерево в неясном состоянии (HEAD=$h) — не цель. Сам не откатываю: это может быть чужая работа. НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора. Лог: $LOG"
    set_off
    exit 1
  fi
  log "НАЙДЕН МАРКЕР ПРЕРВАННОЙ ДОСТАВКИ (HEAD=$h, дерево на цели) — откатываю и разбираюсь заново"
  # Раннер волны — такой же писатель, как юнит кампании, только чужой: убивать его
  # автомат не вправе (это боевой контур). Раз ждать бесполезно, дерево не трогаем
  # вовсе — то же правило 2, что и для кампании (ревью Sol, раунд 19).
  w=$(wait_writers)
  if [ "$w" != ok ]; then
    log "ЖИВОЙ РАННЕР ВОЛНЫ (ждал ${WRITER_WAIT:-120}s) — дерево не трогаю (HEAD=$h), глушу автомат"
    tg_durable "🆘 FotMob: прошлая доставка оборвалась (HEAD=$h), но в дереве работает раннер волны. Откат отменён: менять файлы под живым писателем нельзя. НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора. Лог: $LOG"
    set_off
    exit 1
  fi
  rescue_diff
  # Маркер приёмки снимаем ВМЕСТЕ с откатом: иначе он остался бы говорить «этот
  # SHA принят», и дерево, вернувшееся на цель мимо автомата, снова выглядело бы
  # принятым (ревью Sol, раунд 28).
  rm -f "$ACCEPTED"
  git -C "$TREE" checkout -f "$ROLLBACK_REF" >> "$LOG" 2>&1
  sleep 90
  # Маркер снимаем ТОЛЬКО по подтверждённому откату, иначе автомат замолчал бы
  # с деревом в неизвестном состоянии (ревью Sol, раунд 2).
  if why=$(confirm_rollback); then
    log "восстановление подтверждено: $why"
    tg_durable "⚠️ FotMob: прошлая доставка оборвалась на середине (HEAD был $h). Дерево возвращено: $why.${RESCUE_NOTE} Кампания остановлена. Следующая попытка — в ближайшее окно."
    rm -f "$INFLIGHT"
  else
    # Сначала сообщаем, потом глушим: смерть между этими шагами оставила бы
    # вечный OFF без единого алерта (ревью Sol, раунд 4).
    log "ВОССТАНОВЛЕНИЕ НЕ УДАЛОСЬ: $why — глушу автомат"
    tg_durable "🆘 FotMob: доставка оборвалась и вернуть дерево не удалось ($why).${RESCUE_NOTE} НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора."
    set_off
  fi
  exit 1
fi

# ---- 1. Уже доставлено? Идемпотентность по факту, а не по флагу --------------
head_now=$(head_of)
dirty_now=$(dirty_of)
# У боевого дерева ровно два законных состояния, и оба ЧИСТЫЕ: откатное и
# принятое. Правки отслеживаемых файлов означают, что код правили на месте —
# принятый перестал быть принятым, откатный перестал быть известным. Ждать окна
# нельзя (это до 20 часов тишины), откатывать нельзя (затрём живую правку —
# память dpf-prod-tree-trino-tuning-uncommitted). Зовём руки сразу.
# Прежде «доставлено» считалось по одному HEAD, и грязная цель проходила как
# принятая: автомат обходил приёмку и мог поднять кампанию на непринятом коде
# (ревью Sol, раунд 9).
legal=0
case "$head_now" in "$TARGET"*|"$ROLLBACK_SHA"*) legal=1 ;; esac
# Неотслеживаемый файл в dags/ исполняется наравне с принятым кодом, хотя
# `git status --untracked-files=no` его не видит (ревью Sol, раунд 11).
udags=$(untracked_dags)
if [ "$dirty_now" != 0 ] || [ "$legal" = 0 ] || [ "$udags" != 0 ]; then
  # Кампанию гасим ПЕРВОЙ и всегда: код под ней не принят, а её драйвер переживёт
  # и выключатель, и смерть автомата — иначе он продолжал бы гнать юниты, пока все
  # следующие тики упираются в .off (ревью Sol, раунд 10).
  stop_campaign
  log "ДЕРЕВО ВНЕ ЗАКОННЫХ СОСТОЯНИЙ (HEAD=$head_now, законный SHA: $legal, правок отслеживаемых файлов: $dirty_now, посторонних файлов в dags/: $udags) — глушу автомат"
  tg_durable "🆘 FotMob: боевое дерево не в одном из двух законных состояний (HEAD=$head_now, правок отслеживаемых файлов: $dirty_now, посторонних файлов в dags/: $udags). Ни доставлять, ни откатывать не берусь: это может быть чужая работа. Кампания остановлена.${STOP_NOTE} НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора. Лог: $LOG"
  set_off
  exit 1
fi
delivered=0
case "$head_now" in "$TARGET"*) delivered=1 ;; esac
# Дерево на цели — ещё не «принято». Пустой (или заново созданный) каталог
# состояния делал эти два состояния неотличимыми: маркер незакрытой доставки при
# успехе просто СНИМАЛСЯ, и постоянного следа приёмки не оставалось (ревью Sol,
# раунд 28). Поэтому у дерева на цели спрашиваем маркер принятого SHA, а если его
# нет — подтверждаем приёмку заново, прямо сейчас: это один запрос к метабазе.
if [ "$delivered" = 0 ]; then
  # Дерево на откате — значит принятого кода в бою СЕЙЧАС нет, и маркер приёмки
  # больше ничего не подтверждает (ревью Sol, раунд 29). Неудачу удаления пропускать
  # нельзя: сохранившееся подтверждение говорило бы о коде, которого в бою нет.
  if [ -e "$ACCEPTED" ] || [ -L "$ACCEPTED" ]; then
    rm -f "$ACCEPTED" 2>/dev/null
    if [ -e "$ACCEPTED" ] || [ -L "$ACCEPTED" ]; then
      log "НЕ МОГУ СНЯТЬ МАРКЕР ПРИЁМКИ $ACCEPTED при дереве на откате — глушу автомат"
      tg_durable "🆘 FotMob: дерево на откате, но снять маркер приёмки ($ACCEPTED) не удалось — он продолжал бы подтверждать код, которого в бою нет. НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора. Лог: $LOG"
      set_off
      exit 1
    fi
  fi
fi
# Дерево на цели — ещё не «принято». Маркеру тут веры нет: внешняя цепочка
# «откатили и вернули цель» может целиком уложиться между двумя тиками, и тогда
# сохранившийся маркер соврёт (ревью Sol, раунд 30). Поэтому у дерева на цели
# приёмку спрашиваем У МЕТАБАЗЫ на КАЖДОМ заходе — это один запрос раз в пять минут.
# Окно свежести здесь шире, чем при самой доставке (15 минут): планировщик мог
# перезапускаться, и отставший парсинг не повод глушить автомат.
if [ "$delivered" = 1 ]; then
  acc_seen=$(acceptance_seen "${ACCEPT_FRESH_MIN:-60}")
  case "$acc_seen" in
    1)
      # Маркер остаётся следом для человека и для разбора, решения он не принимает.
      case "$(read_accepted)" in
        "$TARGET"*) : ;;
        *) put_accepted "$head_now" && log "приёмка подтверждена (целевой $NEW_CODE_FILE в контейнере, контур жив), маркер восстановлен" \
             || log "маркер приёмки $ACCEPTED не записан — приёмку подтверждает метабаза, повторю следующим заходом" ;;
      esac
      ;;
    X)
      # Вслепую не решаем: метабаза/контейнер недоступны — ни принять, ни забраковать.
      # Кампанию не трогаем, но и не глушимся: это может быть минутный сбой.
      log "дерево на цели, проверить приёмку нечем (метабаза или scheduler-контейнер недоступны / md5 не прочитан) — кампанию не трогаю"
      if ! said_today "$STATE/fotmob-accept-unknown-$(date -u +%F)"; then
        tg_durable "⚠️ FotMob: дерево на цели, но проверить приёмку нечем — метабаза или scheduler-контейнер не отвечают (или md5 не прочитан). Кампанию не трогаю до выяснения. Лог: $LOG"
        mark_said "$STATE/fotmob-accept-unknown-$(date -u +%F)"
      fi
      exit 0
      ;;
    *)
      stop_campaign
      log "ДЕРЕВО НА ЦЕЛИ, НО ПРИЁМКА НЕ ПОДТВЕРЖДЕНА (md5 $NEW_CODE_FILE не целевой, fotmob-даги не перечитаны или есть ошибки импорта; ответ '$acc_seen') — глушу автомат"
      tg_durable "🆘 FotMob: боевое дерево стоит на целевом коде, но приёмка не подтверждена — md5 $NEW_CODE_FILE не целевой, fotmob-даги не перечитаны или есть ошибки импорта. Кампанию не поднимаю: код мог быть переключён мимо автомата.${STOP_NOTE} НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора. Лог: $LOG"
      set_off
      exit 1
      ;;
  esac
fi
# Дерево на откате — состояние законное, гейт его пропускает. Но кампания имеет
# право работать ТОЛЬКО на целевом коде: там writer-lock (B7) и ретрай коммита
# (#1199). Драйвер переживает и откат, и смерть автомата, а ветка проверки
# драйвера ниже требует delivered=1 — то есть при откате его никто не гасил, и два
# писателя ходили бы в bronze без защиты и без единого слова (ревью Sol, раунд 13).
# Жив может быть и один юнит без драйвера (драйвер сняли, а юнит в контейнере
# остался) — он такой же писатель, поэтому вход в ветку смотрит на обоих.
if [ "$delivered" = 0 ] && { driver_alive || unit_alive; }; then
  if stop_campaign; then
    if ! said_today "$STATE/fotmob-campaign-on-rollback-$(date -u +%F)"; then
      tg_durable "⚠️ FotMob: кампания истории работала при дереве на $head_now (не цель) — остановил. Без B7 и ретрая коммита два писателя ходят в bronze без защиты. Лог: $LOG"
      mark_said "$STATE/fotmob-campaign-on-rollback-$(date -u +%F)"
    fi
  else
    # Писатель на непринятом коде, которого не берёт даже KILL, — это руки, а не
    # суточный маркер: молчать до завтра тут нельзя (ревью Sol, раунд 16).
    log "КАМПАНИЯ НА ОТКАТЕ И НЕ ОСТАНАВЛИВАЕТСЯ — глушу автомат"
    tg_durable "🆘 FotMob: кампания истории работает при дереве на $head_now (не цель) и не останавливается.${STOP_NOTE} Два писателя ходят в bronze без защиты. НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора. Лог: $LOG"
    set_off
    exit 1
  fi
fi
# Подменённый маркер наблюдения при УЖЕ МЁРТВОМ драйвере не попадал ни в ветку
# усыновления, ни в проверки здоровья: обе спрашивают «обычный ли это файл» или
# «жив ли процесс», и автомат доходил до конца и выходил нулём — без алерта и без
# выключателя (ревью Sol, раунд 21). Кампания при этом остаётся неподнятой и
# неоплаканной, а следующий тик повторит то же самое.
if [ "$delivered" = 1 ] && odd_path "$CAMPAIGN_STARTED"; then
  stop_campaign
  log "НА МЕСТЕ МАРКЕРА НАБЛЮДЕНИЯ ($CAMPAIGN_STARTED) НЕ ОБЫЧНЫЙ ФАЙЛ — наблюдение за кампанией не работает, глушу автомат"
  tg_durable "🆘 FotMob: на месте маркера наблюдения за кампанией ($CAMPAIGN_STARTED) не обычный файл — понять, поднята ли кампания, нельзя, а проверки её здоровья молча обходятся. Кампанию остановил.${STOP_NOTE} НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора. Лог: $LOG"
  set_off
  exit 1
fi
# Драйвер может быть жив БЕЗ маркера наблюдения: автомат мог умереть между его
# запуском и созданием маркера. Без маркера все проверки здоровья кампании ниже
# обходятся, и писатель работает никем не наблюдаемый (ревью Sol, раунд 15).
if [ "$delivered" = 1 ] && ! is_plain "$CAMPAIGN_STARTED" && pgrep -f "$CAMPAIGN/driver.sh" >/dev/null 2>&1; then
  log "найден живой драйвер кампании без маркера наблюдения — беру под наблюдение"
  mark_started
fi
# Доставлено И кампания РЕАЛЬНО жива — автомату делать нечего. Проверять надо
# процесс, а не маркер: с одним лишь маркером умерший драйвер не заметил бы никто
# (ревью Sol, раунд 4), и кампания молча стояла бы сутками.
if [ "$delivered" = 1 ] && is_plain "$CAMPAIGN_STARTED"; then
  if pgrep -f "$CAMPAIGN/driver.sh" >/dev/null 2>&1; then
    # Живой процесс — ещё не работающая кампания: при недоступной метабазе
    # contour_busy() вечно отвечает «занято», и драйвер спит без единого сигнала
    # (ревью Sol, раунд 5). Пульс он обновляет каждый виток (BACKOFF=300 с).
    hb=$CAMPAIGN/state/heartbeat
    # Пульс читают `grep` и `find`. Подменённый на FIFO путь повесил бы автомат
    # навсегда — вместе с замком, и все следующие тики выходили бы по нему молча,
    # без алерта и без выключателя (ревью Sol, раунд 26). Читаем только обычный файл.
    if odd_path "$hb"; then
      log "НА МЕСТЕ ПУЛЬСА $hb НЕ ОБЫЧНЫЙ ФАЙЛ — судить о здоровье кампании нечем, глушу автомат"
      tg_durable "🆘 FotMob: на месте пульса кампании ($hb) не обычный файл — о её здоровье судить нечем, а читать такой путь опасно. НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора. Лог: $LOG"
      set_off
      exit 1
    fi
    # Пульс несёт не только время, но и СОСТОЯНИЕ. «disabled» у драйвера, который мы
    # сами пометили запущенным, означает, что маркер campaign_enabled исчез или не
    # создался: драйвер вечно крутится вхолостую, пульс при этом свежий, и снаружи
    # это выглядело здоровой кампанией (ревью Sol, раунд 13).
    if grep -q " disabled$" "$hb" 2>/dev/null; then
      if ! said_today "$STATE/fotmob-campaign-disabled-$(date -u +%F)"; then
        tg_durable "⚠️ FotMob: драйвер кампании жив, но крутится вхолостую (пульс говорит disabled — нет $CAMPAIGN/state/campaign_enabled). Работы нет. Лог: $CAMPAIGN/state/driver.log"
        mark_said "$STATE/fotmob-campaign-disabled-$(date -u +%F)"
      fi
      log "кампания: драйвер в состоянии DISABLED — работы нет"
    fi
    if [ -n "$(find "$hb" -mmin +25 2>/dev/null)" ] || [ ! -f "$hb" ]; then
      if ! said_today "$STATE/fotmob-campaign-stale-$(date -u +%F)"; then
        tg_durable "⚠️ FotMob: драйвер кампании жив, но пульс не обновлялся больше 25 минут (метабаза недоступна?). Смотреть $CAMPAIGN/state/driver.log"
        mark_said "$STATE/fotmob-campaign-stale-$(date -u +%F)"
        log "кампания: пульс просрочен (heartbeat старше 25 мин)"
      fi
    fi
    exit 0
  fi
  # Драйвер умер без явного FAILED. Поднять его можно только в окне (юнит держит
  # замок писателя), поэтому вне окна автомат вышел бы молча — а смерть кампании
  # должна быть слышна сразу (ревью Sol, раунд 7).
  log "кампания помечена запущенной, но драйвер не жив — подниму заново в ближайшее окно"
  # Вход в эту ветку сам требует CAMPAIGN_STARTED, поэтому снимать маркер можно
  # только тогда, когда сообщение о смерти гарантированно дойдёт: иначе упавший
  # Telegram навсегда закрыл бы единственную ветку, которая о ней говорит (ревью
  # Sol, раунд 8). Гарантию даёт очередь tg_durable (раунд 9) — оттого маркер и
  # снимается безусловно.
  if ! said_today "$STATE/fotmob-campaign-dead-$(date -u +%F)"; then
    tg_durable "⚠️ FotMob: драйвер кампании истории умер без причины в state/FAILED. Подниму в ближайшее окно; лог $CAMPAIGN/state/driver.log"
    mark_said "$STATE/fotmob-campaign-dead-$(date -u +%F)"
  fi
  rm -f "$CAMPAIGN_STARTED"
fi

# ---- 2. Окно -----------------------------------------------------------------
# Не боевое дерево (репетиция на копии) — окна нет и проверять нечего. Боевую
# проверку обойти отсюда нельзя: её делает и сам b6-скрипт.
# Проверка окна — только когда есть что доставлять. Раньше она стояла на пути и у
# доставленного дерева: смерть между снятием маркера доставки и запуском кампании
# оставляла кампанию неподнятой, а следующий тик вне окна выходил здесь молча —
# без алерта и без выключателя (ревью Sol, раунд 22). Кампанию поднимать можно в
# любой час: её собственное окно сторожит драйвер (WINDOW_HEAD_GUARD_MIN).
if [ "$IS_PROD" = 1 ] && [ "$delivered" = 0 ]; then
  hm=$((10#$(date -u +%H%M)))
  # Окно кончается, а бой всё ещё не на целевом коде — сказать вслух один раз за
  # ночь. Без этого повторилась бы ровно та беда, ради которой автомат и заведён:
  # окно прошло, доставки нет, и никто не заметил (пять вечеров подряд, урок 111).
  # Молчаливых причин не остаться — живой раннер, недоступная метабаза, смерть
  # между защёлкой и запуском доставки — довольно, а видно их только в логе.
  if [ "$hm" -ge 2300 ] && [ "$hm" -le 2320 ] \
     && ! said_today "$STATE/fotmob-window-missed-$(date -u +%F)"; then
    tg_durable "⚠️ FotMob: окно закрывается, а доставка B6 так и не состоялась (дерево на $head_now). Причина — в $LOG; следующая попытка завтра."
    mark_said "$STATE/fotmob-window-missed-$(date -u +%F)"
  fi
  { [ "$hm" -ge 1945 ] && [ "$hm" -le 2320 ]; } || exit 0

  n=$( { pgrep -f 'dags/scripts/run_fotmob_scrape[r].py' || true; } | wc -l )
  act=$(metadb "SELECT count(*) FROM dag_run WHERE dag_id='dag_ingest_fotmob' AND state IN ('running','queued');")
  # X (метабаза недоступна) — не окно: вслепую не переключаемся. Причину пишем
  # в лог на каждом тике окна: иначе «почему сегодня не доставилось» негде взять.
  if ! { [ "$n" = 0 ] && [ "$act" = 0 ]; }; then
    log "окно закрыто: живых раннеров $n, активных ранов '$act' (X = метабаза недоступна)"
    exit 0
  fi
fi

# ---- 3. Доставка -------------------------------------------------------------
if [ "$delivered" = 0 ]; then
  # Одна попытка за сутки. Без этой защёлки cron повторял бы цикл
  # «переключил → откатил» каждые 5 минут все 3,5 часа окна: десятки подмен
  # боевого дерева под живым DagFileProcessor и полсотни сообщений в TG.
  # Именно -f: защёлка, подменённая symlink-ом на /dev/null или каталогом, при
  # проверке `-e` выглядела бы вечно взведённой, и доставки не было бы никогда —
  # молча (ревью Sol, раунд 16).
  if is_plain "$ATTEMPTED"; then
    exit 0
  fi
  # Без работающей защёлки доставку начинать нельзя: cron повторял бы цикл
  # «переключил → откатил» каждые пять минут всё окно.
  if ! mk_marker "$ATTEMPTED"; then
    log "НЕ СМОГ создать суточную защёлку $ATTEMPTED — доставку не начинаю, глушу автомат"
    tg_durable "🆘 FotMob: не могу создать суточную защёлку ($ATTEMPTED) — без неё доставка повторялась бы каждые 5 минут. Доставки не будет. НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора. Лог: $LOG"
    set_off
    exit 1
  fi

  log "ОКНО ОТКРЫТО (раннеров 0, активных ранов 0) — запускаю $DELIVER apply"
  # Единственное сообщение, которое НЕ дожимается очередью: «начинаю» ценно только
  # вовремя, а исход доставки в любом случае придёт отдельным durable-алертом.
  tg "🚚 FotMob: окно открыто, начинаю доставку B6 (автомат)"

  # Без маркера намерения доставку начинать нельзя: смерть между checkout и
  # приёмкой стала бы неотличима от успеха.
  if ! mk_marker "$INFLIGHT"; then
    log "НЕ СМОГ создать маркер $INFLIGHT — доставку не начинаю"
    tg_durable "🆘 FotMob: автомат не смог создать маркер доставки ($INFLIGHT) — доставка отменена, нужен разбор."
    exit 1
  fi
  # Таймаут обязателен: зависший docker exec или сьют оставил бы дерево
  # переключённым, замок захваченным, а человека — без единого сообщения.
  # FOTMOB_DELIVERY_LOCK=held — эстафета замка: b6 знает, что flock уже наш.
  # Одноразовый пропуск. Проверок замка мало: тот, кто открыл дескриптор и сам
  # взял замок, проходил их все (ревью Sol, раунд 22). Пропуск кладётся в файл
  # состояния и передаётся значением; b6 сверяет и СРАЗУ удаляет файл, так что
  # второй раз тот же пропуск не сработает. Против root-а, сознательно
  # воспроизводящего весь протокол, защиты нет и быть не может — цель в другом:
  # чтобы ручной запуск «по памяти» не прошёл мимо маркера, отката и алертов.
  NONCE_FILE=$STATE/fotmob-deliver-nonce
  nonce=$(openssl rand -hex 16 2>/dev/null)
  if [ -z "$nonce" ] || ! mk_marker "$NONCE_FILE" \
     || ! { printf '%s\n' "$nonce" > "$NONCE_FILE"; } 2>/dev/null; then
    log "НЕ МОГУ ВЫПИСАТЬ ПРОПУСК ДОСТАВКИ ($NONCE_FILE) — доставку не начинаю"
    tg_durable "🆘 FotMob: не могу выписать одноразовый пропуск доставки ($NONCE_FILE) — доставки не будет. НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора. Лог: $LOG"
    set_off
    exit 1
  fi
  TREE="$TREE" FOTMOB_DELIVERY_LOCK=held FOTMOB_DELIVER_NONCE="$nonce" \
    FOTMOB_DELIVER_NONCE_FILE="$NONCE_FILE" \
    timeout -k 30 "$DELIVER_TIMEOUT" "$DELIVER" apply >> "$LOG" 2>&1
  rc=$?
  rm -f "$NONCE_FILE"
  [ "$rc" = 124 ] && log "ТАЙМАУТ доставки (${DELIVER_TIMEOUT}s)"
  head_after=$(head_of)

  ok=0
  if [ "$rc" = 0 ]; then
    case "$head_after" in "$TARGET"*) ok=1 ;; esac
    [ "$ok" = 1 ] || log "rc=0, но HEAD=$head_after не равен цели — считаю доставку несостоявшейся"
    # Доказательство, что контейнер перечитал дерево: DAG из нового кода в метабазе.
    # import_error=0 сам по себе этого не доказывает (ревью Sol 25.08).
    if [ "$ok" = 1 ]; then
      # md5 модуля в контейнере виден сразу после checkout (bind-mount), но «контур
      # перечитан» требует свежего last_parsed_time у живого дага: планировщик
      # пересматривает файлы раз в `dag_dir_list_interval` (по умолчанию 300 с),
      # а b6 ждёт только 90 — держим прежний запас ожидания (урок первой боевой
      # попытки 25.08, откатившейся при исправной доставке).
      seen=0
      accept_left=${ACCEPT_WAIT:-480}
      while :; do
        seen=$(acceptance_seen 15)
        [ "$seen" = 1 ] && break
        [ "$accept_left" -le 0 ] && break
        log "приёмки пока нет (ответ '$seen'), жду ещё ${accept_left}s"
        sleep "${ACCEPT_POLL:-20}"
        accept_left=$((accept_left - ${ACCEPT_POLL:-20}))
      done
      if [ "$seen" != 1 ]; then
        log "НЕТ ДОКАЗАТЕЛЬСТВА ПРИЁМКИ: целевой md5 $NEW_CODE_FILE / перечитанные fotmob-даги без ошибок импорта не подтверждены (ответ '$seen', ждали ${ACCEPT_WAIT:-480}s)"
        ok=0
      else
        # Между предполётным гейтом и этим местом прошли доставка, 90 с ожидания и
        # сьют — минуты. Правка отслеживаемого файла в этот интервал сделала бы
        # «доставленным» дерево, которого никто не принимал (раунд 7); ровно то же
        # верно и для постороннего файла в dags/ — он уже исполняется, а приёмка
        # объявлялась успешной и поднимала драйвер (ревью Sol, раунд 12).
        d_post=$(dirty_of); u_post=$(untracked_dags)
        if [ "$d_post" != 0 ] || [ "$u_post" != 0 ]; then
          log "НЕТ ПРИЁМКИ: после доставки правок отслеживаемых файлов $d_post, посторонних файлов в dags/ $u_post"
          ok=0
        else
          log "приёмка подтверждена: целевой $NEW_CODE_FILE в контейнере, контур перечитан, дерево чисто"
        fi
      fi
    fi
  fi

  if [ "$ok" = 1 ]; then
    log "ДОСТАВЛЕНО: HEAD=$head_after"
    # Постоянный след приёмки: по нему следующие тики отличат принятый код от
    # просто «дерева на нужном SHA» (ревью Sol, раунд 28).
    put_accepted "$head_after" || log "маркер приёмки $ACCEPTED не записан — приёмку подтвердит следующий заход"
    # Маркер снимаем ПОСЛЕ гарантированной отправки: смерть между снятием и
    # сообщением оставила бы исход немым, а суточная защёлка — следующие тики
    # молчаливыми (ревью Sol, раунд 19).
    tg_durable "✅ FotMob B6 доставлен ($head_after), приёмка подтверждена. Волна нового кода родится в 23:55 UTC."
    rm -f "$INFLIGHT"
  else
    log "ПРОВАЛ доставки: rc=$rc, HEAD=$head_after"
    # Решение принимается по ФАКТУ на этот момент, а не по снимку состояния до
    # попытки: снимок устаревал, и правка, появившаяся между ним и доставкой,
    # выглядела бы нашей — автомат уничтожил бы её откатом (ревью Sol, раунд 9).
    # Ровно три исхода:
    #   rollback  — дерево на цели: переключали заведомо мы, откатываем;
    #   untouched — дерево чисто на откате: ничего не делали, просто сообщаем;
    #   hands     — всё прочее: доказательств, что трогали мы, нет; при этом бой
    #               стоит на принятом откатном коде — терпимо, разбирают руки.
    dirty_after=$(dirty_of)
    mode=hands
    case "$head_after" in "$TARGET"*) mode=rollback ;; esac
    if [ "$mode" = hands ] && [ "$dirty_after" = 0 ]; then
      case "$head_after" in "$ROLLBACK_SHA"*) mode=untouched ;; esac
    fi

    # Кампанию гасим ПЕРВОЙ: на откатанном коде у неё нет ни замка писателя (B7),
    # ни ретрая коммита (#1199), а её драйвер переживает и откат, и смерть автомата.
    stop_campaign
    # Пока писатель жив, дерево не трогаем ни в одной из трёх веток ниже: откат
    # под ним испортил бы и его работу, и сам откат (ревью Sol, раунд 17).
    if [ -n "$STOP_NOTE" ]; then
      log "ПИСАТЕЛЬ КАМПАНИИ НЕ ОСТАНОВЛЕН — дерево не трогаю (HEAD=$head_after), глушу автомат"
      tg_durable "🆘 FotMob: доставка провалилась (rc=$rc, HEAD=$head_after), и остановить кампанию не удалось.${STOP_NOTE} Дерево НЕ откатываю: менять файлы под живым писателем нельзя. НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора. Лог: $LOG"
      set_off
      exit 1
    fi

    if [ "$mode" = hands ]; then
      # INFLIGHT НЕ снимаем: он заставляет выключатель напоминать о себе раз в
      # сутки, иначе OFF был бы немым. Разрушительным этот маркер больше не
      # становится: секция 0б тоже откатывает только дерево на цели.
      log "ДЕРЕВО В НЕЯСНОМ СОСТОЯНИИ (HEAD=$head_after, правок=$dirty_after) — доказательств, что трогали мы, нет; глушу автомат"
      tg_durable "🆘 FotMob: доставка провалилась, дерево в неясном состоянии (HEAD=$head_after, правок отслеживаемых файлов: $dirty_after) — ни цель, ни чистый откат. Сам не откатываю: это может быть чужая работа. НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора. Лог: $LOG"
      set_off
      exit 1
    fi

    if [ "$mode" = rollback ]; then
      # Откат безусловный и идемпотентный: гадать по HEAD нельзя — прерванный
      # checkout мог оставить файлы новее, чем говорит ссылка.
      w=$(wait_writers)
      if [ "$w" != ok ]; then
        log "ЖИВОЙ РАННЕР ВОЛНЫ (ждал ${WRITER_WAIT:-120}s) — дерево не трогаю (HEAD=$head_after), глушу автомат"
        tg_durable "🆘 FotMob: доставка провалилась (rc=$rc, HEAD=$head_after), но в дереве работает раннер волны. Откат отменён: менять файлы под живым писателем нельзя. НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора. Лог: $LOG"
        set_off
        exit 1
      fi
      rescue_diff
      rm -f "$ACCEPTED"   # см. выше: принятым считается только подтверждённый SHA
      git -C "$TREE" checkout -f "$ROLLBACK_REF" >> "$LOG" 2>&1
      sleep 90
      if why=$(confirm_rollback); then
        log "ОТКАТ ПОДТВЕРЖДЁН: $why"
        tg_durable "⛔ FotMob B6 не доставлен (код $rc, приёмка не подтверждена). Откат подтверждён: $why.${RESCUE_NOTE} Кампания остановлена. Разбор: $LOG"
        rm -f "$INFLIGHT"
      else
        # Дерево в неизвестном состоянии — дальше только руками. Сначала алерт,
        # потом выключатель (смерть между шагами не должна оставить немой OFF).
        log "ОТКАТ НЕ ПОДТВЕРЖДЁН: $why — глушу автомат"
        tg_durable "🆘 FotMob: доставка провалилась И откат не подтверждён ($why).${RESCUE_NOTE} НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора. Лог: $LOG"
        set_off
      fi
    else
      log "дерево не переключалось (HEAD=$head_after) — откат не требуется"
      tg_durable "⚠️ FotMob B6 не доставлен (rc=$rc, предполётная проверка). Дерево не тронуто, следующая попытка — завтра в окно. Разбор: $LOG"
      rm -f "$INFLIGHT"
    fi
    exit 1
  fi
fi

# ---- 4. Кампания истории (только после успешной доставки) --------------------
# До B6 в бою нет ни writer-lock (B7), ни ретрая коммита (#1199) — запускать
# драйвер было нельзя. После доставки оба на месте.
if pgrep -f "$CAMPAIGN/driver.sh" >/dev/null 2>&1; then
  mark_started
  log "кампания уже запущена — второй драйвер не поднимаю"
  exit 0
fi

# Драйвер сам себя остановил (бан источника, дрейф схемы, застой) — поднимать его
# заново нельзя: повтор бана только усугубит. Файл снимает человек после разбора
# (ревью Sol, раунд 6).
if [ -f "$CAMPAIGN/state/FAILED" ]; then
  if ! said_today "$STATE/fotmob-campaign-failed-reminded-$(date -u +%F)"; then
    tg_durable "⛔ FotMob: кампания истории остановилась сама — $(head -c 200 "$CAMPAIGN/state/FAILED"). Заново не поднимаю. Разбор и снятие $CAMPAIGN/state/FAILED — руками."
    mark_said "$STATE/fotmob-campaign-failed-reminded-$(date -u +%F)"
  fi
  log "кампания в состоянии FAILED — не поднимаю"
  exit 1
fi

# Дерево обязано стоять на цели: кампании нужен код с writer-lock (B7) и ретраем
# коммита (#1199), иначе два писателя ходят в bronze без защиты.
h=$(head_of)
case "$h" in
  "$TARGET"*) : ;;
  *)
    # Единственный молчаливый выход, найденный собственным аудитом всех точек
    # выхода: `delivered` определён в секции 1, а HEAD перечитан здесь — между
    # ними дерево может уехать. Итог выглядел как удачная доставка без кампании,
    # и об этом не узнавал никто. Выключатель не ставим: незаконное состояние
    # поймает гейт секции 1 следующим тиком, а законное (уехали на откат) —
    # причина не запускать кампанию, а не поломка.
    log "кампанию не запускаю: дерево на $h, а не на $TARGET"
    if ! said_today "$STATE/fotmob-campaign-head-drift-$(date -u +%F)"; then
      tg_durable "⚠️ FotMob: доставка считалась удачной, но перед запуском кампании дерево оказалось на $h, а не на $TARGET. Кампанию не поднимаю. Лог: $LOG"
      mark_said "$STATE/fotmob-campaign-head-drift-$(date -u +%F)"
    fi
    exit 1 ;;
esac

# Одного HEAD мало: отслеживаемая правка или новый даг, появившиеся уже ПОСЛЕ
# приёмки, HEAD не меняют — и позволяли запустить драйвер на непринятом дереве
# (ревью Sol, раунд 13). Проверяем ровно те же три величины, что и гейт секции 1.
d_pre=$(dirty_of); u_pre=$(untracked_dags)
if [ "$d_pre" != 0 ] || [ "$u_pre" != 0 ]; then
  # Это то же самое незаконное состояние, что ловит гейт секции 1, и обходиться с
  # ним надо так же: непринятый код уже исполняется. Ждать следующего тика (до пяти
  # минут) незачем — глушим сразу (ревью Sol, раунд 14).
  stop_campaign
  log "ДЕРЕВО НЕ ЧИСТО ПЕРЕД ЗАПУСКОМ КАМПАНИИ (правок $d_pre, посторонних в dags/ $u_pre) — глушу автомат"
  tg_durable "🆘 FotMob: дерево на цели, но не чисто (правок $d_pre, посторонних в dags/ $u_pre) — кампанию не поднимаю.${STOP_NOTE} НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора. Лог: $LOG"
  set_off
  exit 1
fi

# Каталоги кампании обязаны быть НАСТОЯЩИМИ каталогами, и проверить это надо ДО
# первой же операции с их содержимым: ссылка на месте `state` или `logs` уводит
# разом всё — удаление STOP, выключатель кампании, приёмник вывода драйвера, — а
# проверки конечных путей её не видят: цель ссылки выглядит обычным файлом
# (ревью Sol, раунд 24). Драйвер такую подмену тоже ловит, но уже ПОСЛЕ того, как
# автомат отработал по чужим путям и открыл nohup-лог.
for d in "$CAMPAIGN/state" "$CAMPAIGN/logs"; do
  if [ -L "$d" ] || [ ! -d "$d" ]; then
    log "НА МЕСТЕ КАТАЛОГА КАМПАНИИ $d НЕ КАТАЛОГ — кампанию не поднимаю"
    tg_durable "🆘 FotMob: на месте каталога кампании $d не каталог — запись ушла бы по ссылке. Кампанию не поднимаю. НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора. Лог: $LOG"
    set_off
    exit 1
  fi
done

# STOP мог остаться от прошлого провала — иначе свежий драйвер умрёт на первом же
# витке цикла, и автомат будет поднимать труп каждые пять минут.
rm -f "$CAMPAIGN/state/STOP"
# Создание маркера проверяем: если его не записать (нет места, на месте каталог),
# драйвер поднимется и будет ВЕЧНО крутиться в ветке DISABLED, обновляя пульс, —
# снаружи это выглядит здоровой кампанией (ревью Sol, раунд 13).
# Через mk_marker: подменённый на symlink выключатель кампании принимает запись с
# нулевым кодом, автомат объявляет кампанию запущенной, а драйвер вечно сидит в
# ветке DISABLED с бодрым пульсом — снаружи здоровая кампания, работы ноль
# (ревью Sol, раунд 20).
if ! mk_marker "$CAMPAIGN/state/campaign_enabled"; then
  log "НЕ МОГУ СОЗДАТЬ $CAMPAIGN/state/campaign_enabled — драйвер не поднимаю"
  tg_durable "🆘 FotMob: не могу создать $CAMPAIGN/state/campaign_enabled — кампанию не поднимаю, иначе драйвер вечно крутился бы вхолостую. НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора. Лог: $LOG"
  # Без выключателя следующий тик повторил бы ту же неудачу — и так каждые пять
  # минут до утра, с тем же сообщением (ревью Sol, раунд 25).
  set_off
  exit 1
fi
# 9>&- обязателен: без него драйвер наследует дескриптор flock-замка и держит его
# все недели своей жизни — следующий запуск автомата молча выходил бы по замку
# (поймано репетицией 25.08).
# TREE и EXPECT_SHA передаём явно: у драйвера есть свои дефолты, но два источника
# правды рано или поздно разъедутся, а расходиться им нельзя — по этим значениям
# драйвер сам аттестует дерево перед каждым юнитом (ревью Sol, раунд 14).
# Отдельный приёмник вывода драйвера — такой же путь для записи, как лог автомата:
# подменённый, он увёл бы вывод (в том числе в файл боевого дерева), причём мимо
# всех проверок самого драйвера (ревью Sol, раунд 23).
if odd_path "$CAMPAIGN/logs/driver-nohup.log"; then
  log "НА МЕСТЕ ЛОГА ЗАПУСКА ДРАЙВЕРА ($CAMPAIGN/logs/driver-nohup.log) НЕ ОБЫЧНЫЙ ФАЙЛ — кампанию не поднимаю"
  tg_durable "🆘 FotMob: на месте лога запуска драйвера ($CAMPAIGN/logs/driver-nohup.log) не обычный файл — вывод ушёл бы по ссылке. Кампанию не поднимаю. НУЖНЫ РУКИ. Автомат глушу: снять $OFF после разбора. Лог: $LOG"
  set_off
  exit 1
fi
TREE="$TREE" EXPECT_SHA="$TARGET" \
  setsid nohup "$CAMPAIGN/driver.sh" >> "$CAMPAIGN/logs/driver-nohup.log" 2>&1 9>&- &
sleep 5
if pgrep -f "$CAMPAIGN/driver.sh" >/dev/null 2>&1; then
  mark_started
  rm -f "$STARTFAILS"
  log "кампания истории запущена (driver.sh жив)"
  tg_durable "🏁 FotMob: кампания истории запущена (очередь 3201 пара, драйвер уступает волнам)"
else
  # Маркер НЕ ставим: следующий запуск автомата попробует поднять драйвер снова —
  # разовая неудача (контейнер перезапускался) лечится повтором. Но повторять
  # БЕСКОНЕЧНО нельзя: драйвер, валящийся на старте, означает, что автомат раз в
  # пять минут пишет в те же пути и шлёт то же сообщение (ревью Sol, раунд 24).
  # Счётчик живёт в каталоге автомата, а не кампании: путь кампании и мог оказаться
  # тем, из-за чего драйвер не встаёт. Подменённый счётчик = исчерпанные попытки.
  # Читаем ТОЛЬКО обычный файл и только после проверки: `cat` по FIFO повис бы
  # навсегда, держа flock, и все следующие тики выходили бы по замку — молча, без
  # алерта и без выключателя (ревью Sol, раунд 25).
  if odd_path "$STARTFAILS"; then
    fails=$START_FAILS_MAX
    log "на месте $STARTFAILS не обычный файл — считаю попытки исчерпанными"
  else
    fails=$( { cat "$STARTFAILS" 2>/dev/null || true; } | tr -cd '0-9' | head -c 2)
    fails=$(( ${fails:-0} + 1 ))
    # Не записался счётчик — значит следующий тик начнёт с нуля и автомат будет
    # повторять попытку вечно. Такой повтор хуже остановки: считаем исчерпанным.
    if ! { printf '%s\n' "$fails" > "$STARTFAILS"; } 2>/dev/null || ! is_plain "$STARTFAILS"; then
      log "не могу записать счётчик попыток $STARTFAILS — считаю попытки исчерпанными"
      fails=$START_FAILS_MAX
    fi
  fi
  log "ВНИМАНИЕ: драйвер кампании не поднялся (попытка $fails из $START_FAILS_MAX)"
  if [ "$fails" -ge "$START_FAILS_MAX" ]; then
    tg_durable "🆘 FotMob: драйвер кампании не поднялся $fails раза подряд — больше не пробую. НУЖНЫ РУКИ: $CAMPAIGN/state/driver.log и $CAMPAIGN/logs/driver-nohup.log. Автомат глушу: снять $OFF после разбора. Лог: $LOG"
    set_off
  else
    tg_durable "⚠️ FotMob: B6 доставлен, но драйвер кампании не поднялся (попытка $fails из $START_FAILS_MAX) — смотреть $CAMPAIGN/state/driver.log"
  fi
  exit 1
fi
exit 0
